//! T2 byte-identity anchor: golden logits for the batched-prefill KV-dtype
//! paths.
//!
//! These fixtures were captured from the SIX
//! `forward_prefill_batched_*_inner` copies **before** they were collapsed
//! into one generic `forward_prefill_batched_inner<K: BatchedKv>`, and are
//! asserted **bit-exact** after. The refactor is mechanical and
//! behavior-preserving, so a single changed float here is a regression.
//!
//! Coverage: both LM-head modes (`Last` + `All`), the tree-verify path, all
//! six KV dtypes (F32 / Q8_0 / TQ / NVFP4 / Q4_0 / MXFP4·6·8), the Q4_0
//! whitening quirk (head_dim % 64 == 0), and the MoE FFN arm (dense-expert +
//! quant).
//!
//! Capture protocol: when a `GOLDEN_*` constant is empty the check prints the
//! current values as a paste-ready `const` and passes; once filled it asserts
//! bit-exact. Run with `-- --nocapture --test-threads=1` to (re)capture.

use rustllama_gguf::synth::{write_synthetic_llama_gguf, SynthLlama, SynthMoe};
use rustllama_gguf::Gguf;
use rustllama_models::llama_arch::{KvCache, KvDtype, LlamaModel};

const TOKENS: [i32; 6] = [3, 5, 7, 11, 13, 17];

fn load(tag: &str, params: &SynthLlama) -> LlamaModel {
    let tmp = std::env::temp_dir().join(format!("rustllama-golden-{tag}.gguf"));
    write_synthetic_llama_gguf(&tmp, params);
    let gguf = Gguf::open(&tmp).expect("open synth gguf");
    let model = LlamaModel::load_allow_moe(&gguf).expect("load synth");
    let _ = std::fs::remove_file(&tmp);
    model
}

/// Bit-exact compare. On mismatch (or an empty golden) print the captured
/// values as a paste-ready `const`; empty golden => capture mode (pass),
/// non-empty mismatch => fail.
fn check(name: &str, logits: &[f32], golden: &[u32]) {
    for (i, v) in logits.iter().enumerate() {
        assert!(v.is_finite(), "{name}: non-finite logit[{i}] = {v}");
    }
    let got: Vec<u32> = logits.iter().map(|v| v.to_bits()).collect();
    if !golden.is_empty() && got == *golden {
        return;
    }
    let mut s = format!("\nconst {name}: &[u32] = &[\n");
    for (i, b) in got.iter().enumerate() {
        if i % 6 == 0 {
            s.push_str("    ");
        }
        s.push_str(&format!("0x{b:08x}, "));
        if i % 6 == 5 {
            s.push('\n');
        }
    }
    s.push_str("\n];");
    if golden.is_empty() {
        println!("[golden-capture]{s}");
    } else {
        panic!("golden mismatch for {name} — NOT byte-identical:{s}");
    }
}

fn all_logits(model: &LlamaModel, out_len_mult: usize) -> Vec<f32> {
    vec![0f32; out_len_mult * model.cfg.vocab_size]
}

// ---- F32: Last / All / tree-verify ----

#[test]
fn golden_f32_last() {
    let m = load("f32", &SynthLlama::default());
    let mut kv = KvCache::new(&m.cfg, 32);
    let logits = m.forward_prefill_batched_f32(&TOKENS, 0, &mut kv);
    check("GOLDEN_F32_LAST", &logits, GOLDEN_F32_LAST);
}

#[test]
fn golden_f32_all() {
    let m = load("f32all", &SynthLlama::default());
    let mut kv = KvCache::new(&m.cfg, 32);
    let mut out = all_logits(&m, TOKENS.len());
    m.forward_speculation_batched_f32(&TOKENS, 0, &mut kv, &mut out);
    check("GOLDEN_F32_ALL", &out, GOLDEN_F32_ALL);
}

#[test]
fn golden_f32_tree() {
    let m = load("f32tree", &SynthLlama::default());
    let mut kv = KvCache::new(&m.cfg, 32);
    // Chain tree (depths == index, parent == index-1): exercises the tree
    // attention path and reduces to the linear spec forward.
    let depths: [u32; 6] = [0, 1, 2, 3, 4, 5];
    let parent: [i32; 6] = [-1, 0, 1, 2, 3, 4];
    let mut out = all_logits(&m, TOKENS.len());
    m.forward_tree_verify_f32(&TOKENS, 0, &depths, &parent, &mut kv, &mut out);
    check("GOLDEN_F32_TREE", &out, GOLDEN_F32_TREE);
}

