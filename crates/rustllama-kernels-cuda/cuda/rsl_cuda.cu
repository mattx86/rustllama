// ---- extern "C" launchers ----
// Shared shape guard for the quantized-KV flash launchers. `blk_elems`
// is the format's block width (32 Q4_0, 16 NVFP4) or 0 for TurboQuant
// (power-of-two head_dim). Returns 0 if the shape is dispatchable.
static int rsl_flash_kv_shape_ok(int n_heads, int n_kv_heads, int head_dim,
                                 int max_ctx, int blk_elems) {
    if (n_heads <= 0 || n_kv_heads <= 0 || head_dim <= 0 || max_ctx <= 0) return -1;
    if ((n_heads % n_kv_heads) != 0) return -1;
    if (head_dim > RSL_FLASH_MAX_HEAD_DIM) return -1;
    if (blk_elems > 0) {
        if ((head_dim % blk_elems) != 0) return -1;
    } else {
        // TurboQuant: head_dim must be a power of two for the WHT.
        if ((head_dim & (head_dim - 1)) != 0) return -1;
    }
    return 0;
}

extern "C" int rsl_cuda_flash_attn_decode_q4_0(rsl_cuda_stream *s, const float *q,
                                               const void *k_packed, const void *v_packed,
                                               float *out, int n_heads, int n_kv_heads,
                                               int head_dim, int max_ctx, int kv_len) {
    if (!s || !q || !k_packed || !v_packed || !out) return -1;
    if (rsl_flash_kv_shape_ok(n_heads, n_kv_heads, head_dim, max_ctx, 32) != 0) return -1;
    cudaSetDevice(s->device);
    if (kv_len <= 0) {
        cudaMemsetAsync(out, 0, (size_t)n_heads * head_dim * sizeof(float), s->stream);
        return rsl_cuda_check("rsl_cuda_flash_attn_decode_q4_0");
    }
    int n_gqa = n_heads / n_kv_heads;
    float scale = 1.0f / sqrtf((float)head_dim);
    int t = 64, b = (n_heads + t - 1) / t;
    flash_attn_decode_q4_0_kernel<<<b, t, 0, s->stream>>>(
        q, (const unsigned char *)k_packed, (const unsigned char *)v_packed, out,
        n_heads, n_gqa, head_dim, max_ctx, kv_len, scale);
    return rsl_cuda_check("rsl_cuda_flash_attn_decode_q4_0");
}

