// Add-residual + RMSNorm fused (mirrors rsl_add_rmsnorm_usm):
//   hidden[i] += branch[i]                      (residual, in place)
//   y_norm[i]  = rmsnorm(hidden_row)[i] * w[i]  (pre-norm output)
// One block per row; block-reduce the sum of squares.
__global__ void add_rmsnorm_f32_kernel(float *hidden, const float *branch,
                                       const float *w, float *y_norm,
                                       int d, float eps) {
    int row = blockIdx.x;
    float *hr = hidden + (size_t)row * d;
    float *yr = y_norm + (size_t)row * d;
    const float *br = branch + (size_t)row * d;
    __shared__ float sh[256];
    float local = 0.f;
    for (int i = threadIdx.x; i < d; i += blockDim.x) {
        float v = hr[i] + br[i];
        hr[i] = v;
        local += v * v;
    }
    sh[threadIdx.x] = local;
    __syncthreads();
    for (int s = blockDim.x >> 1; s > 0; s >>= 1) {
        if (threadIdx.x < s) sh[threadIdx.x] += sh[threadIdx.x + s];
        __syncthreads();
    }
    float inv = rsqrtf(sh[0] / (float)d + eps);
    for (int i = threadIdx.x; i < d; i += blockDim.x) yr[i] = hr[i] * inv * w[i];
}

extern "C" int rsl_cuda_add_rmsnorm_f32(rsl_cuda_stream *s, float *hidden,
                                        const float *branch, const float *w,
                                        float *y_norm, int n_rows, int d,
                                        float eps) {
    if (!s || !hidden || !branch || !w || !y_norm || n_rows <= 0 || d <= 0)
        return -1;
    cudaSetDevice(s->device);
    int threads = d < 256 ? d : 256;
    // round threads up to a power of two <= 256 for the reduction tree
    int t = 1;
    while (t < threads) t <<= 1;
    if (t > 256) t = 256;
    add_rmsnorm_f32_kernel<<<n_rows, t, 0, s->stream>>>(hidden, branch, w,
                                                        y_norm, d, eps);
    return rsl_cuda_check("rsl_cuda_add_rmsnorm_f32");
}

// RoPE (mirrors rsl_rope_usm): rotate the (j, j+half) pair of each head
// by angle = pos * inv_freq[j]. qk is [n_heads, head_dim]; inv_freq is
// [head_dim/2] precomputed inverse frequencies. One thread per (head, j).
__global__ void rope_f32_kernel(float *qk, int n_heads, int head_dim, int pos,
                                const float *inv_freq) {
    int half = head_dim / 2;
    int total = n_heads * half;
    int flat = blockIdx.x * blockDim.x + threadIdx.x;
    if (flat >= total) return;
    int head = flat / half;
    int j = flat % half;
    float angle = (float)pos * inv_freq[j];
    float c = cosf(angle), si = sinf(angle);
    int base = head * head_dim;
    float x0 = qk[base + j];
    float x1 = qk[base + j + half];
    qk[base + j] = x0 * c - x1 * si;
    qk[base + j + half] = x0 * si + x1 * c;
}

extern "C" int rsl_cuda_rope_f32(rsl_cuda_stream *s, float *qk, int n_heads,
                                 int head_dim, int pos, const float *inv_freq) {
    if (!s || !qk || !inv_freq || n_heads <= 0 || head_dim <= 0 ||
        (head_dim % 2) != 0)
        return -1;
    cudaSetDevice(s->device);
    int total = n_heads * (head_dim / 2);
    int t = 128, b = (total + t - 1) / t;
    rope_f32_kernel<<<b, t, 0, s->stream>>>(qk, n_heads, head_dim, pos, inv_freq);
    return rsl_cuda_check("rsl_cuda_rope_f32");
}

// SwiGLU (mirrors rsl_silu_mul_usm): out[i] = silu(x[i]) * y[i].
__global__ void silu_mul_f32_kernel(const float *x, const float *y, float *out,
                                    int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i >= n) return;
    float xv = x[i];
    float silu = xv / (1.0f + expf(-xv));
    out[i] = silu * y[i];
}

extern "C" int rsl_cuda_silu_mul_f32(rsl_cuda_stream *s, const float *x,
                                     const float *y, float *out, int n) {
    if (!s || !x || !y || !out || n <= 0) return -1;
    cudaSetDevice(s->device);
    int t = 256, b = (n + t - 1) / t;
    silu_mul_f32_kernel<<<b, t, 0, s->stream>>>(x, y, out, n);
    return rsl_cuda_check("rsl_cuda_silu_mul_f32");
}

// Embedding lookup (mirrors rsl_embedding_lookup_usm): out[i] = table[ids[i]]
// (d elements). ids < 0 → zero row. `ids` is a DEVICE pointer here (the CUDA
// worker uploads it) — no host scratch like the SYCL variant. One block per id.
__global__ void embedding_lookup_f32_kernel(const float *table,
                                            const int *ids, float *out,
                                            int n_ids, int d) {
    int i = blockIdx.x;
    if (i >= n_ids) return;
    int row = ids[i];
    float *o = out + (size_t)i * d;
    if (row < 0) {
        for (int j = threadIdx.x; j < d; j += blockDim.x) o[j] = 0.f;
        return;
    }
    const float *tr = table + (size_t)row * d;
    for (int j = threadIdx.x; j < d; j += blockDim.x) o[j] = tr[j];
}

extern "C" int rsl_cuda_embedding_lookup_f32(rsl_cuda_stream *s,
                                             const float *table, const int *ids,
                                             float *out, int n_ids, int d) {
    if (!s || !table || !ids || !out || n_ids <= 0 || d <= 0) return -1;
    cudaSetDevice(s->device);
    int t = d < 256 ? d : 256;
    embedding_lookup_f32_kernel<<<n_ids, t, 0, s->stream>>>(table, ids, out,
                                                            n_ids, d);
    return rsl_cuda_check("rsl_cuda_embedding_lookup_f32");
}

// FlashAttention decode, F32 (mirrors rsl_flash_attn_decode_usm v1):
//   q:   [n_heads, head_dim]
//   k/v: [n_kv_heads, max_ctx, head_dim]
//   out: [n_heads, head_dim]
// One thread per head; serial online softmax over kv_len positions.
__global__ void flash_attn_decode_f32_kernel(const float *q, const float *k,
                                             const float *v, float *out,
                                             int n_heads, int n_gqa,
                                             int head_dim, int max_ctx,
                                             int kv_len, float scale) {
    int hh = blockIdx.x * blockDim.x + threadIdx.x;
    if (hh >= n_heads) return;
    int kv_h = hh / n_gqa;
    int q_base = hh * head_dim;
    int out_base = hh * head_dim;
    for (int i = 0; i < head_dim; ++i) out[out_base + i] = 0.f;
    float m = -INFINITY, l = 0.f;
    for (int t = 0; t < kv_len; ++t) {
        int k_off = (kv_h * max_ctx + t) * head_dim;
        float s_dot = 0.f;
        for (int i = 0; i < head_dim; ++i) s_dot += q[q_base + i] * k[k_off + i];
        s_dot *= scale;
        float m_new = fmaxf(m, s_dot);
        float rescale = isfinite(m) ? expf(m - m_new) : 0.f;
        float p = expf(s_dot - m_new);
        l = l * rescale + p;
        int v_off = (kv_h * max_ctx + t) * head_dim;
        for (int i = 0; i < head_dim; ++i)
            out[out_base + i] = out[out_base + i] * rescale + p * v[v_off + i];
        m = m_new;
    }
    float inv_l = (l > 0.f) ? 1.f / l : 0.f;
    for (int i = 0; i < head_dim; ++i) out[out_base + i] *= inv_l;
}

extern "C" int rsl_cuda_flash_attn_decode_f32(rsl_cuda_stream *s,
                                              const float *q, const float *k,
                                              const float *v, float *out,
                                              int n_heads, int n_kv_heads,
                                              int head_dim, int max_ctx,
                                              int kv_len) {
    if (!s || !q || !k || !v || !out) return -1;
    if (n_heads <= 0 || n_kv_heads <= 0 || head_dim <= 0 || max_ctx <= 0)
        return -1;
    if ((n_heads % n_kv_heads) != 0) return -1;
    cudaSetDevice(s->device);
    if (kv_len <= 0) {
        cudaMemsetAsync(out, 0, (size_t)n_heads * head_dim * sizeof(float),
                        s->stream);
        return rsl_cuda_check("rsl_cuda_flash_attn_decode_f32");
    }
    int n_gqa = n_heads / n_kv_heads;
    float scale = 1.0f / sqrtf((float)head_dim);
    int t = 64, b = (n_heads + t - 1) / t;
    flash_attn_decode_f32_kernel<<<b, t, 0, s->stream>>>(
        q, k, v, out, n_heads, n_gqa, head_dim, max_ctx, kv_len, scale);
    return rsl_cuda_check("rsl_cuda_flash_attn_decode_f32");
}

// FlashAttention prefill, F32 (mirrors rsl_flash_attn_prefill_usm):
//   q:   [n_new, n_heads, head_dim]  row-major
//   k/v: [n_kv_heads, max_ctx, head_dim]
//   out: [n_new, n_heads, head_dim]  row-major
// Causal: query at new position q_pos attends absolute [0, kv_len_base+q_pos].
// 2D grid: x = head, y = q_pos. One thread per (head, q_pos).
// head_dim ceiling, shared with the quantized-KV flash kernels below (the
// #ifndef at the quant-KV block then sees it already defined and skips). The
// per-lane register slices (qreg/acc) are sized for this ceiling.
#ifndef RSL_FLASH_MAX_HEAD_DIM
#define RSL_FLASH_MAX_HEAD_DIM 256
#endif

// Warp-cooperative tiled FlashAttention-2 prefill (f32). The naive version
// this replaces ran one thread per (head, q_pos) and re-streamed all of K/V
// from global for every query — O(n_new) redundant reads of the same K/V.
// Here a block is BQ warps (BQ*32 threads) and ONE warp owns one query row,
// so the BQ warps in a block share each staged K/V tile (the reuse win). K/V
// are streamed in tiles of BK positions through dynamic shared memory; the
// q·k dot is split across the 32 lanes of a warp and finished with a shuffle
// reduction; the softmax is the SAME online (running-max) recurrence as the
// CPU/scalar reference, so the result matches it to within FMA/expf
// reassociation. Causal masking is a per-query inner-loop bound (`jmax`); the
// OUTER tile-loop bound is block-uniform (`p_block_max`) so every warp — even
// a tail warp whose q_pos is out of range — reaches the same __syncthreads.
//
// Shared use = 2*BK*head_dim*4 B = 16 KB at head_dim 128, 32 KB at 256 — under
// the 48 KB per-block floor guaranteed on every CUDA arch, so no opt-in / no
// device capability query is needed. Block = 128 threads (<< the 1024 cap).
#define RSL_FLASH_PREFILL_BQ 4   // query rows (warps) per block
#define RSL_FLASH_PREFILL_BK 16  // KV positions staged per shared tile
__global__ void flash_attn_prefill_f32_kernel(const float *q, const float *k,
                                              const float *v, float *out,
                                              int n_heads, int n_gqa,
                                              int head_dim, int max_ctx,
                                              int kv_len_base, int n_new,
                                              float scale) {
    extern __shared__ float smem[];  // [BK*head_dim] K then [BK*head_dim] V
    float *k_tile = smem;
    float *v_tile = smem + RSL_FLASH_PREFILL_BK * head_dim;

    const int lane = threadIdx.x;              // 0..31
    const int warp = threadIdx.y;              // 0..BQ-1
    const int tid = warp * 32 + lane;
    const int nthreads = blockDim.x * blockDim.y;

    const int hh = blockIdx.y;                 // attention head
    const int q_base = blockIdx.x * RSL_FLASH_PREFILL_BQ;
    const int q_pos = q_base + warp;           // this warp's query row
    const int kv_h = hh / n_gqa;

    const bool active = (q_pos < n_new);
    // Absolute KV position this query attends up to, inclusive (causal). The
    // tile loop bound uses the block's MAX q_pos so it is warp-uniform.
    const int q_last = min(q_base + RSL_FLASH_PREFILL_BQ - 1, n_new - 1);
    const int p_self = kv_len_base + q_pos;    // meaningful only if active
    const int p_block_max = kv_len_base + q_last;

    // Each lane owns head dims {lane, lane+32, ...}; qreg/acc hold that slice.
    float qreg[(RSL_FLASH_MAX_HEAD_DIM + 31) / 32];
    float acc[(RSL_FLASH_MAX_HEAD_DIM + 31) / 32];
    if (active) {
        const int q_off = (q_pos * n_heads + hh) * head_dim;
        for (int seg = 0, d = lane; d < head_dim; ++seg, d += 32) {
            qreg[seg] = q[q_off + d];
            acc[seg] = 0.f;
        }
    }
    float m = -INFINITY, l = 0.f;

    for (int t0 = 0; t0 <= p_block_max; t0 += RSL_FLASH_PREFILL_BK) {
        __syncthreads();
        // Cooperatively stage K/V tile [t0, t0+BK) for this kv head. All
        // threads (active or not) participate so the staging is complete.
        for (int e = tid; e < RSL_FLASH_PREFILL_BK * head_dim; e += nthreads) {
            int j = e / head_dim;
            int d = e - j * head_dim;
            int t = t0 + j;
            float kk = 0.f, vv = 0.f;
            if (t < max_ctx) {
                int kv_off = (kv_h * max_ctx + t) * head_dim;
                kk = k[kv_off + d];
                vv = v[kv_off + d];
            }
            k_tile[e] = kk;
            v_tile[e] = vv;
        }
        __syncthreads();
        if (active) {
            // Causal: this query sees positions t0..min(t0+BK-1, p_self).
            int jmax = min(RSL_FLASH_PREFILL_BK, p_self - t0 + 1);
            for (int j = 0; j < jmax; ++j) {
                const float *krow = k_tile + j * head_dim;
                float partial = 0.f;
                for (int seg = 0, d = lane; d < head_dim; ++seg, d += 32)
                    partial += qreg[seg] * krow[d];
                // Warp reduce the per-lane partials into lane 0, broadcast back.
                #pragma unroll
                for (int off = 16; off > 0; off >>= 1)
                    partial += __shfl_down_sync(0xffffffffu, partial, off);
                float s_dot = __shfl_sync(0xffffffffu, partial, 0) * scale;
                float m_new = fmaxf(m, s_dot);
                float rescale = isfinite(m) ? expf(m - m_new) : 0.f;
                float p = expf(s_dot - m_new);
                l = l * rescale + p;
                const float *vrow = v_tile + j * head_dim;
                for (int seg = 0, d = lane; d < head_dim; ++seg, d += 32)
                    acc[seg] = acc[seg] * rescale + p * vrow[d];
                m = m_new;
            }
        }
    }
    if (active) {
        float inv_l = (l > 0.f) ? 1.f / l : 0.f;
        const int out_off = (q_pos * n_heads + hh) * head_dim;
        for (int seg = 0, d = lane; d < head_dim; ++seg, d += 32)
            out[out_off + d] = acc[seg] * inv_l;
    }
}

extern "C" int rsl_cuda_flash_attn_prefill_f32(rsl_cuda_stream *s,
                                               const float *q, const float *k,
                                               const float *v, float *out,
                                               int n_heads, int n_kv_heads,
                                               int head_dim, int max_ctx,
                                               int kv_len_base, int n_new) {
    if (!s || !q || !k || !v || !out) return -1;
    if (n_heads <= 0 || n_kv_heads <= 0 || head_dim <= 0 || max_ctx <= 0 ||
        n_new <= 0)
        return -1;
    if ((n_heads % n_kv_heads) != 0) return -1;
    if (head_dim > RSL_FLASH_MAX_HEAD_DIM) return -1;
    if (kv_len_base < 0 || kv_len_base + n_new > max_ctx) return -1;
    cudaSetDevice(s->device);
    int n_gqa = n_heads / n_kv_heads;
    float scale = 1.0f / sqrtf((float)head_dim);
    dim3 block(32, RSL_FLASH_PREFILL_BQ);  // 128 threads, 1 warp per query row
    dim3 grid((n_new + RSL_FLASH_PREFILL_BQ - 1) / RSL_FLASH_PREFILL_BQ,
              (unsigned)n_heads);
    size_t shmem =
        (size_t)2 * RSL_FLASH_PREFILL_BK * head_dim * sizeof(float);
    flash_attn_prefill_f32_kernel<<<grid, block, shmem, s->stream>>>(
        q, k, v, out, n_heads, n_gqa, head_dim, max_ctx, kv_len_base, n_new,
        scale);
    return rsl_cuda_check("rsl_cuda_flash_attn_prefill_f32");
}

// Greedy argmax over an F32 logits buffer (mirrors rsl_sampler_argmax_usm):
// writes the index of the max logit to out_idx[0]. Single block; each thread
// strides the vocab, then a block reduction picks the winner (lowest index
// on ties, matching the CPU reference's first-max semantics).
__global__ void argmax_f32_kernel(const float *logits, int vocab,
                                  int *out_idx) {
    __shared__ float sval[256];
    __shared__ int sidx[256];
    int tid = threadIdx.x;
    float best = -INFINITY;
    int besti = -1;
    for (int i = tid; i < vocab; i += blockDim.x) {
        float v = logits[i];
        if (v > best) { best = v; besti = i; }
    }
    sval[tid] = best;
    sidx[tid] = besti;
    __syncthreads();
    for (int s = blockDim.x >> 1; s > 0; s >>= 1) {
        if (tid < s) {
            float ov = sval[tid + s];
            int oi = sidx[tid + s];
            // Prefer strictly-greater; on equal value prefer the lower index.
            if (ov > sval[tid] || (ov == sval[tid] && oi >= 0 &&
                                   (sidx[tid] < 0 || oi < sidx[tid]))) {
                sval[tid] = ov;
                sidx[tid] = oi;
            }
        }
        __syncthreads();
    }
    if (tid == 0) out_idx[0] = sidx[0];
}

extern "C" int rsl_cuda_argmax_f32(rsl_cuda_stream *s, const float *logits,
                                   int vocab, int *out_idx) {
    if (!s || !logits || !out_idx || vocab <= 0) return -1;
    cudaSetDevice(s->device);
    argmax_f32_kernel<<<1, 256, 0, s->stream>>>(logits, vocab, out_idx);
    return rsl_cuda_check("rsl_cuda_argmax_f32");
}

// ============================================================
// Quantized-KV FlashAttention (F32 Q / F32 out, packed K/V
// dequantized on the fly). The online-softmax recurrence is
// byte-for-byte the F32 flash kernels above; only the K/V source
// differs — instead of reading F32 cache rows, each work-item
// dequantizes one packed K (then V) row into a private register
// buffer per kv position, matching the CPU reference exactly:
//   Q4_0-KV      -> rustllama-kernels-cpu/src/q4_0_kv.rs
//   NVFP4-KV     -> rustllama-kernels-cpu/src/nvfp4.rs
//   TurboQuant   -> rustllama-kernels-cpu/src/turboquant.rs
// The CPU kernels dequantize a whole row into an f32 scratch, then
// run `online_softmax_attn_f32_scratch` over it — so dequantizing
// the full row here (rather than fusing the dequant into the dot)
// reproduces the CPU float op order. One thread per head (decode)
// or per (head, q_pos) (prefill). head_dim is capped so the private
// row buffer is a fixed size; the launcher rejects larger shapes so
// the caller falls back to the CPU kernel.
// ============================================================

#ifndef RSL_FLASH_MAX_HEAD_DIM
#define RSL_FLASH_MAX_HEAD_DIM 256
#endif

// Dequant one Q4_0 KV row (head_dim elems, head_dim % 32 == 0). Block
// = 18 B / 32: f16 d + 16 nibble bytes; weight = (nibble - 8) * d.
__device__ __forceinline__ void rsl_deq_q4_0_row(const unsigned char *p,
                                                 float *row, int head_dim) {
    int nb = head_dim / 32;
    for (int b = 0; b < nb; ++b) {
        const unsigned char *blk = p + b * 18;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs = blk + 2;
        int o = b * 32;
        for (int j = 0; j < 16; ++j) {
            row[o + j]      = (float)((int)(qs[j] & 0x0F) - 8) * d;
            row[o + j + 16] = (float)((int)(qs[j] >> 4) - 8) * d;
        }
    }
}

// Dequant one NVFP4 KV row (head_dim % 16 == 0). Block = 9 B / 16:
// 8 nibble bytes (lo->2j, hi->2j+1) + FP8 E4M3 scale byte. Reuses the
// module-level RSL_NVFP4_CODEBOOK + rsl_e4m3_to_f32.
__device__ __forceinline__ void rsl_deq_nvfp4_row(const unsigned char *p,
                                                  float *row, int head_dim) {
    int nb = head_dim / 16;
    for (int b = 0; b < nb; ++b) {
        const unsigned char *blk = p + b * 9;
        float scale = rsl_e4m3_to_f32(blk[8]);
        int o = b * 16;
        for (int j = 0; j < 8; ++j) {
            unsigned char byte = blk[j];
            int lo = byte & 0x0F;
            int hi = (byte >> 4) & 0x0F;
            row[o + j * 2]     = RSL_NVFP4_CODEBOOK[lo] * scale;
            row[o + j * 2 + 1] = RSL_NVFP4_CODEBOOK[hi] * scale;
        }
    }
}

// Dequant one MXFP4 KV row (head_dim % 32 == 0). Block = 17 B / 32:
// 16 nibble bytes packing two E2M1 codes each (low nibble -> elem 2j,
// high -> elem 2j+1) + trailing E8M0 shared-scale byte (byte 16). Reuses
// the module-level RSL_NVFP4_CODEBOOK (E2M1) + rsl_e8m0_to_f32; mirrors
// the mxfp4_row_dot layout but dequants into `row` (no fused dot).
__device__ __forceinline__ void rsl_deq_mxfp4_row(const unsigned char *p,
                                                  float *row, int head_dim) {
    int nb = head_dim / 32;
    for (int b = 0; b < nb; ++b) {
        const unsigned char *blk = p + b * 17;   // 17 B / 32-elem block
        float scale = rsl_e8m0_to_f32(blk[16]);
        int o = b * 32;
        for (int j = 0; j < 16; ++j) {
            unsigned char byte = blk[j];
            int lo = byte & 0x0F;
            int hi = (byte >> 4) & 0x0F;
            row[o + j * 2]     = RSL_NVFP4_CODEBOOK[lo] * scale;
            row[o + j * 2 + 1] = RSL_NVFP4_CODEBOOK[hi] * scale;
        }
    }
}

// Dequant one MXFP6 KV row (head_dim % 32 == 0). Block = 25 B / 32:
// 24-byte LE bitstream of 32 six-bit E3M2 codes (element j at bit 6j, may
// straddle a byte boundary) + trailing E8M0 scale byte (byte 24). Read a
// 16-bit window { codes[byte_idx], codes[byte_idx+1] } and shift right by
// (6j % 8); the high byte reads 0 once past the 24-byte code region (only
// the final code touches it, and its top bits are unused).
__device__ __forceinline__ void rsl_deq_mxfp6_row(const unsigned char *p,
                                                  float *row, int head_dim) {
    int nb = head_dim / 32;
    for (int b = 0; b < nb; ++b) {
        const unsigned char *blk = p + b * 25;   // 25 B / 32-elem block
        const unsigned char *codes = blk;        // qs[0..24]
        float scale = rsl_e8m0_to_f32(blk[24]);
        int o = b * 32;
        for (int j = 0; j < 32; ++j) {
            int bitpos = j * 6;
            int byte_idx = bitpos >> 3;           // bitpos / 8
            int bit_off = bitpos & 7;             // bitpos % 8
            unsigned int lo = codes[byte_idx];
            unsigned int hi = (byte_idx + 1 < 24) ? (unsigned int)codes[byte_idx + 1] : 0u;
            unsigned int word = lo | (hi << 8);
            unsigned char code = (unsigned char)((word >> bit_off) & 0x3Fu);
            row[o + j] = rsl_e3m2_to_f32(code) * scale;
        }
    }
}

// Dequant one MXFP8 KV row (head_dim % 32 == 0). Block = 33 B / 32:
// 32 E4M3 bytes (one per element) + trailing E8M0 scale byte (byte 32).
__device__ __forceinline__ void rsl_deq_mxfp8_row(const unsigned char *p,
                                                  float *row, int head_dim) {
    int nb = head_dim / 32;
    for (int b = 0; b < nb; ++b) {
        const unsigned char *blk = p + b * 33;   // 33 B / 32-elem block
        float scale = rsl_e8m0_to_f32(blk[32]);
        int o = b * 32;
        for (int j = 0; j < 32; ++j) {
            row[o + j] = rsl_e4m3_to_f32(blk[j]) * scale;
        }
    }
}

// Dequant one TurboQuant KV row: unpack signed codes (bits in
// {1,2,4,8}), multiply by the row's separate scale, then inverse WHT
// (forward butterfly + 1/N). Matches turboquant::dequantize_row's op
// order (scale applied BEFORE the transform). head_dim must be a
// power of two (WHT). `p` = ceil(head_dim*bits/8) packed bytes.
__device__ __forceinline__ void rsl_deq_tq_row(const unsigned char *p,
                                               float scale, int bits,
                                               float *row, int head_dim) {
    int max_level = (bits == 1) ? 1 : ((bits == 2) ? 1 : ((bits == 4) ? 7 : 127));
    unsigned mask = (bits == 1) ? 0x1u : ((bits == 2) ? 0x3u : ((bits == 4) ? 0xFu : 0xFFu));
    for (int i = 0; i < head_dim; ++i) {
        int bit_off = i * bits;
        int byte_idx = bit_off >> 3;
        int bit_in = bit_off & 7;
        unsigned cell = (unsigned)p[byte_idx] >> bit_in;
        if (bit_in + bits > 8) {
            int spill = bit_in + bits - 8;
            int shift = bits - spill;
            cell |= (unsigned)p[byte_idx + 1] << shift;
        }
        unsigned u = cell & mask;
        int code = (bits == 1) ? ((u == 0) ? -1 : 1) : ((int)u - max_level);
        row[i] = (float)code * scale;
    }
    // Inverse WHT = forward WHT then * (1/N).
    for (int h = 1; h < head_dim; h <<= 1) {
        for (int i = 0; i < head_dim; i += (h << 1)) {
            for (int j = i; j < i + h; ++j) {
                float a = row[j];
                float bqv = row[j + h];
                row[j]     = a + bqv;
                row[j + h] = a - bqv;
            }
        }
    }
    float inv_n = 1.0f / (float)head_dim;
    for (int i = 0; i < head_dim; ++i) row[i] *= inv_n;
}

// ---- Q4_0-KV decode / prefill ----
__global__ void flash_attn_decode_q4_0_kernel(const float *q,
                                              const unsigned char *k_packed,
                                              const unsigned char *v_packed,
                                              float *out, int n_heads, int n_gqa,
                                              int head_dim, int max_ctx,
                                              int kv_len, float scale) {
    int hh = blockIdx.x * blockDim.x + threadIdx.x;
    if (hh >= n_heads) return;
    int kv_h = hh / n_gqa;
    int q_base = hh * head_dim;
    int out_base = hh * head_dim;
    int bytes_per_row = (head_dim / 32) * 18;
    float row[RSL_FLASH_MAX_HEAD_DIM];
    for (int i = 0; i < head_dim; ++i) out[out_base + i] = 0.f;
    float m = -INFINITY, l = 0.f;
    for (int t = 0; t < kv_len; ++t) {
        const unsigned char *kp = k_packed + (size_t)(kv_h * max_ctx + t) * bytes_per_row;
        rsl_deq_q4_0_row(kp, row, head_dim);
        float s_dot = 0.f;
        for (int i = 0; i < head_dim; ++i) s_dot += q[q_base + i] * row[i];
        s_dot *= scale;
        float m_new = fmaxf(m, s_dot);
        float rescale = isfinite(m) ? expf(m - m_new) : 0.f;
        float p = expf(s_dot - m_new);
        l = l * rescale + p;
        const unsigned char *vp = v_packed + (size_t)(kv_h * max_ctx + t) * bytes_per_row;
        rsl_deq_q4_0_row(vp, row, head_dim);
        for (int i = 0; i < head_dim; ++i)
            out[out_base + i] = out[out_base + i] * rescale + p * row[i];
        m = m_new;
    }
    float inv_l = (l > 0.f) ? 1.f / l : 0.f;
    for (int i = 0; i < head_dim; ++i) out[out_base + i] *= inv_l;
}

