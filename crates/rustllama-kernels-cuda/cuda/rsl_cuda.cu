// ============================================================
// Q8_0-KV FlashAttention (F32 Q / F32 out, i8 KV + per-row f32 scale).
// Byte-exact port of the CPU reference gqa_attention_flash_decode_q8_0 /
// _prefill_q8_0 (rustllama-kernels-cpu/src/lib.rs). NOTE the KV layout here
// differs from the Q4_0/NVFP4/TQ KV kernels above: the engine's KvLayer::Q8_0
// stores K/V as a PLAIN i8 slab [n_kv_heads, max_ctx, head_dim] (one byte per
// element, NO 34B/32 GGUF blocks) plus a separate per-row absmax f32 scale in
// k_scales/v_scales = [n_kv_heads*max_ctx] (indexed kv_h*max_ctx + t) — same
// shape as the TQ scales. Unlike the other quantized-KV kernels, the CPU Q8_0
// reference does NOT materialize a dequantized row: it dots the raw i8 codes,
// then factors the row scale out of the inner loop (s *= k_scale*attn_scale;
// out += (p*v_scale)*i8). We reproduce that factoring exactly for float
// parity, so there is no private per-thread row buffer and head_dim is only
// bounded by the shared shape guard (kept uniform with the other launchers).
__global__ void flash_attn_decode_q8_0_kernel(const float *q,
                                              const signed char *k_q,
                                              const float *k_scales,
                                              const signed char *v_q,
                                              const float *v_scales,
                                              float *out, int n_heads, int n_gqa,
                                              int head_dim, int max_ctx,
                                              int kv_len, float scale) {
    int hh = blockIdx.x * blockDim.x + threadIdx.x;
    if (hh >= n_heads) return;
    int kv_h = hh / n_gqa;
    int q_base = hh * head_dim;
    int out_base = hh * head_dim;
    for (int i = 0; i < head_dim; ++i) out[out_base + i] = 0.f;
    float m = -INFINITY, l = 0.f;
    for (int t = 0; t < kv_len; ++t) {
        size_t ridx = (size_t)(kv_h * max_ctx + t);
        const signed char *kp = k_q + ridx * head_dim;
        float s_dot = 0.f;
        for (int i = 0; i < head_dim; ++i) s_dot += q[q_base + i] * (float)kp[i];
        s_dot *= k_scales[ridx] * scale;
        float m_new = fmaxf(m, s_dot);
        float rescale = isfinite(m) ? expf(m - m_new) : 0.f;
        float p = expf(s_dot - m_new);
        l = l * rescale + p;
        const signed char *vp = v_q + ridx * head_dim;
        float p_eff = p * v_scales[ridx];
        for (int i = 0; i < head_dim; ++i)
            out[out_base + i] = out[out_base + i] * rescale + p_eff * (float)vp[i];
        m = m_new;
    }
    float inv_l = (l > 0.f) ? 1.f / l : 0.f;
    for (int i = 0; i < head_dim; ++i) out[out_base + i] *= inv_l;
}

__global__ void flash_attn_prefill_q8_0_kernel(const float *q,
                                               const signed char *k_q,
                                               const float *k_scales,
                                               const signed char *v_q,
                                               const float *v_scales,
                                               float *out, int n_heads, int n_gqa,
                                               int head_dim, int max_ctx,
                                               int kv_len_base, int n_new,
                                               float scale) {
    int hh = blockIdx.x * blockDim.x + threadIdx.x;
    int q_pos = blockIdx.y;
    if (hh >= n_heads || q_pos >= n_new) return;
    int kv_h = hh / n_gqa;
    int q_off = (q_pos * n_heads + hh) * head_dim;
    int out_off = q_off;
    int kv_len_for_q = kv_len_base + q_pos + 1;
    for (int i = 0; i < head_dim; ++i) out[out_off + i] = 0.f;
    float m = -INFINITY, l = 0.f;
    for (int t = 0; t < kv_len_for_q; ++t) {
        size_t ridx = (size_t)(kv_h * max_ctx + t);
        const signed char *kp = k_q + ridx * head_dim;
        float s_dot = 0.f;
        for (int i = 0; i < head_dim; ++i) s_dot += q[q_off + i] * (float)kp[i];
        s_dot *= k_scales[ridx] * scale;
        float m_new = fmaxf(m, s_dot);
        float rescale = isfinite(m) ? expf(m - m_new) : 0.f;
        float p = expf(s_dot - m_new);
        l = l * rescale + p;
        const signed char *vp = v_q + ridx * head_dim;
        float p_eff = p * v_scales[ridx];
        for (int i = 0; i < head_dim; ++i)
            out[out_off + i] = out[out_off + i] * rescale + p_eff * (float)vp[i];
        m = m_new;
    }
    float inv_l = (l > 0.f) ? 1.f / l : 0.f;
    for (int i = 0; i < head_dim; ++i) out[out_off + i] *= inv_l;
}

