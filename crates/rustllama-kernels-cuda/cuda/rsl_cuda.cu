// Q5_K: 176 B / 256 wts. { d:f16, dmin:f16, scales[12], qh[32], qs[128] }.
__device__ __forceinline__ float q5_k_row_dot(const unsigned char *row,
                                              const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 176;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        unsigned short m_bits = (unsigned short)blk[2] | ((unsigned short)blk[3] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        float dmin = rsl_f16_bits_to_f32(m_bits);
        unsigned char sc[8], mn[8];
        rsl_unpack_q4k_scales(blk + 4, sc, mn);
        const unsigned char *qh = blk + 16;
        const unsigned char *qs = blk + 48;
        const int x_base = b * 256;
        for (int group = 0; group < 4; ++group) {
            const unsigned char *qc = qs + group * 32;
            float d_lo = d * (float)sc[group * 2];
            float m_lo = dmin * (float)mn[group * 2];
            float d_hi = d * (float)sc[group * 2 + 1];
            float m_hi = dmin * (float)mn[group * 2 + 1];
            int bit_lo = group * 2;
            int bit_hi = group * 2 + 1;
            int x_lo = x_base + group * 64;
            int x_hi = x_lo + 32;
            for (int l = 0; l < 32; ++l) {
                unsigned char qb = qc[l];
                unsigned char qhb = qh[l];
                int lo = (int)(qb & 0x0F) | (((qhb >> bit_lo) & 1) << 4);
                int hi = (int)(qb >> 4) | (((qhb >> bit_hi) & 1) << 4);
                acc += (d_lo * (float)lo - m_lo) * x[x_lo + l];
                acc += (d_hi * (float)hi - m_hi) * x[x_hi + l];
            }
        }
    }
    return acc;
}

// Q2_K: 84 B / 256 wts. { scales[16], qs[64], d:f16, dmin:f16 }.
__device__ __forceinline__ float q2_k_row_dot(const unsigned char *row,
                                              const float *x, int bpr) {
    float acc = 0.0f;
    const int shifts[4] = {0, 2, 4, 6};
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 84;
        const unsigned char *scales = blk;
        const unsigned char *qs = blk + 16;
        unsigned short d_bits = (unsigned short)blk[80] | ((unsigned short)blk[81] << 8);
        unsigned short m_bits = (unsigned short)blk[82] | ((unsigned short)blk[83] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        float dmin = rsl_f16_bits_to_f32(m_bits);
        const int x_base = b * 256;
        int x_off = 0, is = 0;
        for (int chunk = 0; chunk < 2; ++chunk) {
            const unsigned char *q = qs + chunk * 32;
            for (int si = 0; si < 4; ++si) {
                int shift = shifts[si];
                unsigned char sc_a = scales[is];
                float dl_a = d * (float)(sc_a & 0x0F);
                float ml_a = dmin * (float)(sc_a >> 4);
                for (int l = 0; l < 16; ++l) {
                    float qv = (float)((q[l] >> shift) & 3);
                    acc += (dl_a * qv - ml_a) * x[x_base + x_off + l];
                }
                x_off += 16;
                is += 1;
                unsigned char sc_b = scales[is];
                float dl_b = d * (float)(sc_b & 0x0F);
                float ml_b = dmin * (float)(sc_b >> 4);
                for (int l = 0; l < 16; ++l) {
                    float qv = (float)((q[l + 16] >> shift) & 3);
                    acc += (dl_b * qv - ml_b) * x[x_base + x_off + l];
                }
                x_off += 16;
                is += 1;
            }
        }
    }
    return acc;
}

// Q8_K: 292 B / 256 wts. { d:f32, qs[256] i8, bsums[16] i16 (unused here) }.
__device__ __forceinline__ float q8_k_row_dot(const unsigned char *row,
                                              const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 292;
        int d_raw = (int)((unsigned)blk[0] | ((unsigned)blk[1] << 8) |
                          ((unsigned)blk[2] << 16) | ((unsigned)blk[3] << 24));
        float d = __int_as_float(d_raw);
        const signed char *qs = (const signed char *)(blk + 4);
        int xo = b * 256;
        for (int j = 0; j < 256; ++j) {
            acc += d * (float)qs[j] * x[xo + j];
        }
    }
    return acc;
}

// Q4_0: 18 B / 32 wts. { d:f16, qs[16] }. nibble - 8, split halves.
__device__ __forceinline__ float q4_0_row_dot(const unsigned char *row,
                                              const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 18;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs = blk + 2;
        int xo = b * 32;
        for (int j = 0; j < 16; ++j) {
            int x0 = (int)(qs[j] & 0x0F) - 8;
            int x1 = (int)(qs[j] >> 4) - 8;
            acc += d * (float)x0 * x[xo + j];
            acc += d * (float)x1 * x[xo + j + 16];
        }
    }
    return acc;
}

// Q5_0: 22 B / 32 wts. { d:f16, qh:u32, qs[16] }. 5th bit from qh, - 16.
__device__ __forceinline__ float q5_0_row_dot(const unsigned char *row,
                                              const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 22;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        unsigned int qh = (unsigned)blk[2] | ((unsigned)blk[3] << 8) |
                          ((unsigned)blk[4] << 16) | ((unsigned)blk[5] << 24);
        const unsigned char *qs = blk + 6;
        int xo = b * 32;
        for (int j = 0; j < 16; ++j) {
            unsigned int xh_0 = ((qh >> j) << 4) & 0x10u;
            unsigned int xh_1 = (qh >> (j + 12)) & 0x10u;
            int x0 = (int)((qs[j] & 0x0F) | xh_0) - 16;
            int x1 = (int)((qs[j] >> 4) | xh_1) - 16;
            acc += d * (float)x0 * x[xo + j];
            acc += d * (float)x1 * x[xo + j + 16];
        }
    }
    return acc;
}

