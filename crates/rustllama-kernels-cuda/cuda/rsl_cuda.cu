// IQ4_XS: 136 B / 256 wts. { d:f16, scales_h:u16, scales_l[4], qs[128] }.
// Eight 6-bit signed sub-scales (bias 32); nibbles index the codebook.
__device__ __forceinline__ float iq4_xs_row_dot(const unsigned char *row,
                                                const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 136;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        unsigned int scales_h = (unsigned)blk[2] | ((unsigned)blk[3] << 8);
        const unsigned char *scales_l = blk + 4;
        const unsigned char *qs = blk + 8;
        const int x_base = b * 256;
        for (int ib = 0; ib < 8; ++ib) {
            int lo_nibble = (ib % 2 == 0) ? (scales_l[ib / 2] & 0x0F)
                                          : (scales_l[ib / 2] >> 4);
            int hi_bits = (scales_h >> (2 * ib)) & 0x03;
            // 6-bit value 0..63 (< 128, so the i8 cast is a no-op) minus 32.
            int ls = (lo_nibble | (hi_bits << 4)) - 32;
            float sub_d = d * (float)ls;
            int q_off = ib * 16;
            int x_off = x_base + ib * 32;
            for (int j = 0; j < 16; ++j) {
                unsigned char q = qs[q_off + j];
                int lo = q & 0x0F;
                int hi = q >> 4;
                acc += sub_d * (float)RSL_KVALUES_IQ4NL[lo] * x[x_off + j];
                acc += sub_d * (float)RSL_KVALUES_IQ4NL[hi] * x[x_off + 16 + j];
            }
        }
    }
    return acc;
}

// IQ2_XXS: 66 B / 256 wts. { d:f16, qs[64] }. Per ib32: two u32 aux words;
// aux0 = 4x 8-bit grid idx, aux1 = 4x 7-bit sign idx + 4-bit scale (top).
__device__ __forceinline__ float iq2_xxs_row_dot(const unsigned char *row,
                                                 const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 66;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs = blk + 2;
        const int x_base = b * 256;
        for (int ib32 = 0; ib32 < 8; ++ib32) {
            const unsigned char *p = qs + 8 * ib32;
            unsigned int aux0 = (unsigned)p[0] | ((unsigned)p[1] << 8) |
                                ((unsigned)p[2] << 16) | ((unsigned)p[3] << 24);
            unsigned int aux1 = (unsigned)p[4] | ((unsigned)p[5] << 8) |
                                ((unsigned)p[6] << 16) | ((unsigned)p[7] << 24);
            float db = d * (0.5f + (float)(aux1 >> 28)) * 0.25f;
            for (int l = 0; l < 4; ++l) {
                unsigned int grid_idx = (aux0 >> (l * 8)) & 0xFFu;
                unsigned long long g = rsl::IQ2XXS_GRID_CUDA[grid_idx];
                unsigned char signs = rsl::KSIGNS_IQ2XS_CUDA[(aux1 >> (7 * l)) & 127u];
                int x_off = x_base + ib32 * 32 + l * 8;
                for (int j = 0; j < 8; ++j) {
                    signed char gj = (signed char)((g >> (j * 8)) & 0xFFu);
                    float s = (signs & rsl::KMASK_IQ2XS_CUDA[j]) ? -1.0f : 1.0f;
                    acc += db * (float)gj * s * x[x_off + j];
                }
            }
        }
    }
    return acc;
}

// IQ2_XS: 74 B / 256 wts. { d:f16, qs[64] (u16 codes), scales[8] }.
// code = 9-bit grid idx | 7-bit sign idx; two 4-bit sub-scales per byte.
__device__ __forceinline__ float iq2_xs_row_dot(const unsigned char *row,
                                                const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 74;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs = blk + 2;
        const unsigned char *scales = blk + 66;
        const int x_base = b * 256;
        for (int ib32 = 0; ib32 < 8; ++ib32) {
            unsigned char scale_byte = scales[ib32];
            float db_lo = d * (0.5f + (float)(scale_byte & 0x0F)) * 0.25f;
            float db_hi = d * (0.5f + (float)(scale_byte >> 4)) * 0.25f;
            for (int l = 0; l < 4; ++l) {
                const unsigned char *qp = qs + 8 * ib32 + 2 * l;
                unsigned int q = (unsigned)qp[0] | ((unsigned)qp[1] << 8);
                unsigned int grid_idx = q & 511u;
                unsigned int sign_idx = q >> 9;
                unsigned long long g = rsl::IQ2XS_GRID_CUDA[grid_idx];
                unsigned char signs = rsl::KSIGNS_IQ2XS_CUDA[sign_idx];
                float db = (l < 2) ? db_lo : db_hi;
                int x_off = x_base + ib32 * 32 + l * 8;
                for (int j = 0; j < 8; ++j) {
                    signed char gj = (signed char)((g >> (j * 8)) & 0xFFu);
                    float s = (signs & rsl::KMASK_IQ2XS_CUDA[j]) ? -1.0f : 1.0f;
                    acc += db * (float)gj * s * x[x_off + j];
                }
            }
        }
    }
    return acc;
}

// IQ2_S: 82 B / 256 wts. { d:f16, qs_lo[32], signs[32], qh[8], scales[8] }.
// 10-bit grid idx (8 low bits + 2 high from qh); sign bytes read directly.
__device__ __forceinline__ float iq2_s_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 82;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs_lo = blk + 2;
        const unsigned char *signs = blk + 34;
        const unsigned char *qh = blk + 66;
        const unsigned char *scales = blk + 74;
        const int x_base = b * 256;
        for (int ib32 = 0; ib32 < 8; ++ib32) {
            unsigned char scale_byte = scales[ib32];
            float db_lo = d * (0.5f + (float)(scale_byte & 0x0F)) * 0.25f;
            float db_hi = d * (0.5f + (float)(scale_byte >> 4)) * 0.25f;
            int qs_off = ib32 * 4;
            unsigned int qh_byte = qh[ib32];
            for (int l = 0; l < 4; ++l) {
                unsigned int high_bits = (qh_byte << (8 - 2 * l)) & 0x300u;
                unsigned int grid_idx = (unsigned)qs_lo[qs_off + l] | high_bits;
                unsigned char sign_byte = signs[qs_off + l];
                unsigned long long g = rsl::IQ2S_GRID_CUDA[grid_idx];
                float db = (l < 2) ? db_lo : db_hi;
                int x_off = x_base + ib32 * 32 + l * 8;
                for (int j = 0; j < 8; ++j) {
                    signed char gj = (signed char)((g >> (j * 8)) & 0xFFu);
                    float s = (sign_byte & rsl::KMASK_IQ2XS_CUDA[j]) ? -1.0f : 1.0f;
                    acc += db * (float)gj * s * x[x_off + j];
                }
            }
        }
    }
    return acc;
}

// IQ3_XXS: 98 B / 256 wts. { d:f16, qs_grid[64] (u8 idx), qs_sas[32] (8xu32) }.
// Each u32 packs 4x 7-bit sign idx (low 28b) + 4-bit scale (top); u32 grid.
__device__ __forceinline__ float iq3_xxs_row_dot(const unsigned char *row,
                                                 const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 98;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs_grid = blk + 2;
        const unsigned char *qs_sas = blk + 66;
        const int x_base = b * 256;
        for (int ib32 = 0; ib32 < 8; ++ib32) {
            const unsigned char *p = qs_sas + 4 * ib32;
            unsigned int aux32 = (unsigned)p[0] | ((unsigned)p[1] << 8) |
                                 ((unsigned)p[2] << 16) | ((unsigned)p[3] << 24);
            float db = d * (0.5f + (float)(aux32 >> 28)) * 0.5f;
            int qs_off = 8 * ib32;
            for (int l = 0; l < 4; ++l) {
                unsigned int g1i = qs_grid[qs_off + 2 * l];
                unsigned int g2i = qs_grid[qs_off + 2 * l + 1];
                unsigned int g1 = rsl::IQ3XXS_GRID_CUDA[g1i];
                unsigned int g2 = rsl::IQ3XXS_GRID_CUDA[g2i];
                unsigned char signs = rsl::KSIGNS_IQ2XS_CUDA[(aux32 >> (7 * l)) & 127u];
                int x_off = x_base + ib32 * 32 + l * 8;
                for (int j = 0; j < 4; ++j) {
                    signed char g1j = (signed char)((g1 >> (j * 8)) & 0xFFu);
                    signed char g2j = (signed char)((g2 >> (j * 8)) & 0xFFu);
                    float s_lo = (signs & rsl::KMASK_IQ2XS_CUDA[j]) ? -1.0f : 1.0f;
                    float s_hi = (signs & rsl::KMASK_IQ2XS_CUDA[j + 4]) ? -1.0f : 1.0f;
                    acc += db * (float)g1j * s_lo * x[x_off + j];
                    acc += db * (float)g2j * s_hi * x[x_off + j + 4];
                }
            }
        }
    }
    return acc;
}

// IQ3_S: 110 B / 256 wts. { d:f16, qs[64], qh[8], signs[32], scales[4] }.
// 9-bit grid idx (8 low bits from qs + 1 high bit from qh); direct signs;
// per-pair scales give two db multipliers (2*(scale nibble)+1).
__device__ __forceinline__ float iq3_s_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 110;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs = blk + 2;
        const unsigned char *qh = blk + 66;
        const unsigned char *signs = blk + 74;
        const unsigned char *scales = blk + 106;
        const int x_base = b * 256;
        int qs_cur = 0, signs_cur = 0;
        for (int pair = 0; pair < 4; ++pair) {
            int ib32 = pair * 2;
            unsigned char scale_byte = scales[pair];
            float db1 = d * (1.0f + 2.0f * (float)(scale_byte & 0x0F));
            float db2 = d * (1.0f + 2.0f * (float)(scale_byte >> 4));
            int x_off1 = x_base + ib32 * 32;
            int x_off2 = x_base + (ib32 + 1) * 32;
            unsigned int qh1 = qh[ib32];
            unsigned int qh2 = qh[ib32 + 1];
            // First 32-weight sub-block (qh1, db1).
            for (int l = 0; l < 4; ++l) {
                unsigned int g1i = (unsigned)qs[qs_cur + 2 * l] | ((qh1 << (8 - 2 * l)) & 0x100u);
                unsigned int g2i = (unsigned)qs[qs_cur + 2 * l + 1] | ((qh1 << (7 - 2 * l)) & 0x100u);
                unsigned int g1 = rsl::IQ3S_GRID_CUDA[g1i];
                unsigned int g2 = rsl::IQ3S_GRID_CUDA[g2i];
                unsigned char sign_byte = signs[signs_cur + l];
                int xl = x_off1 + l * 8;
                for (int j = 0; j < 4; ++j) {
                    signed char g1j = (signed char)((g1 >> (j * 8)) & 0xFFu);
                    signed char g2j = (signed char)((g2 >> (j * 8)) & 0xFFu);
                    float s_lo = (sign_byte & rsl::KMASK_IQ2XS_CUDA[j]) ? -1.0f : 1.0f;
                    float s_hi = (sign_byte & rsl::KMASK_IQ2XS_CUDA[j + 4]) ? -1.0f : 1.0f;
                    acc += db1 * (float)g1j * s_lo * x[xl + j];
                    acc += db1 * (float)g2j * s_hi * x[xl + 4 + j];
                }
            }
            qs_cur += 8;
            signs_cur += 4;
            // Second 32-weight sub-block (qh2, db2).
            for (int l = 0; l < 4; ++l) {
                unsigned int g1i = (unsigned)qs[qs_cur + 2 * l] | ((qh2 << (8 - 2 * l)) & 0x100u);
                unsigned int g2i = (unsigned)qs[qs_cur + 2 * l + 1] | ((qh2 << (7 - 2 * l)) & 0x100u);
                unsigned int g1 = rsl::IQ3S_GRID_CUDA[g1i];
                unsigned int g2 = rsl::IQ3S_GRID_CUDA[g2i];
                unsigned char sign_byte = signs[signs_cur + l];
                int xl = x_off2 + l * 8;
                for (int j = 0; j < 4; ++j) {
                    signed char g1j = (signed char)((g1 >> (j * 8)) & 0xFFu);
                    signed char g2j = (signed char)((g2 >> (j * 8)) & 0xFFu);
                    float s_lo = (sign_byte & rsl::KMASK_IQ2XS_CUDA[j]) ? -1.0f : 1.0f;
                    float s_hi = (sign_byte & rsl::KMASK_IQ2XS_CUDA[j + 4]) ? -1.0f : 1.0f;
                    acc += db2 * (float)g1j * s_lo * x[xl + j];
                    acc += db2 * (float)g2j * s_hi * x[xl + 4 + j];
                }
            }
            qs_cur += 8;
            signs_cur += 4;
        }
    }
    return acc;
}

// IQ1_S: 50 B / 256 wts. { d:f16, qs[32], qh[16] (8x u16) }.
// Per ib32: dl = d*(2*((qh>>12)&7)+1); delta = +/-(1 -/+ 0.125); 11-bit idx.
__device__ __forceinline__ float iq1_s_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    const float IQ1S_DELTA = 0.125f;
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 50;
        unsigned short d_bits = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const unsigned char *qs = blk + 2;
        const unsigned char *qh_bytes = blk + 34;
        const int x_base = b * 256;
        for (int ib32 = 0; ib32 < 8; ++ib32) {
            unsigned int qh = (unsigned)qh_bytes[ib32 * 2] | ((unsigned)qh_bytes[ib32 * 2 + 1] << 8);
            float dl = d * (2.0f * (float)((qh >> 12) & 7) + 1.0f);
            float delta = (qh & 0x8000u) ? (-1.0f - IQ1S_DELTA) : (-1.0f + IQ1S_DELTA);
            int x_off = x_base + ib32 * 32;
            for (int l = 0; l < 4; ++l) {
                unsigned int idx = (unsigned)qs[4 * ib32 + l] | (((qh >> (3 * l)) & 7u) << 8);
                unsigned long long g = rsl::IQ1S_GRID_CUDA[idx];
                for (int j = 0; j < 8; ++j) {
                    signed char gj = (signed char)((g >> (j * 8)) & 0xFFu);
                    acc += dl * ((float)gj + delta) * x[x_off + 8 * l + j];
                }
            }
        }
    }
    return acc;
}

// IQ1_M: 56 B / 256 wts. { qs[32], qh[16], scales[8] (4x u16) }. The block
// d is reassembled from the top nibble of each of the four scale words; each
// 16-weight half carries its own (dl, delta).
__device__ __forceinline__ float iq1_m_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    const float IQ1S_DELTA = 0.125f;
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 56;
        const unsigned char *qs = blk;
        const unsigned char *qh = blk + 32;
        const unsigned char *scb = blk + 48;
        unsigned int sc[4];
        for (int ii = 0; ii < 4; ++ii)
            sc[ii] = (unsigned)scb[ii * 2] | ((unsigned)scb[ii * 2 + 1] << 8);
        unsigned short d_bits = (unsigned short)(((sc[0] >> 12)) |
                                                 ((sc[1] >> 8) & 0x00F0u) |
                                                 ((sc[2] >> 4) & 0x0F00u) |
                                                 ((sc[3]) & 0xF000u));
        float d = rsl_f16_bits_to_f32(d_bits);
        const int x_base = b * 256;
        for (int ib = 0; ib < 8; ++ib) {
            unsigned int s_word = sc[ib / 2];
            int shift0 = 6 * (ib % 2);
            int shift1 = 6 * (ib % 2) + 3;
            float dl1 = d * (2.0f * (float)((s_word >> shift0) & 0x7) + 1.0f);
            float dl2 = d * (2.0f * (float)((s_word >> shift1) & 0x7) + 1.0f);
            unsigned int qh0 = qh[ib * 2];
            unsigned int qh1 = qh[ib * 2 + 1];
            const unsigned char *qc = qs + ib * 4;
            unsigned int idx_l[4] = {
                (unsigned)qc[0] | ((qh0 & 0x07u) << 8),
                (unsigned)qc[1] | (((qh0 >> 4) & 0x07u) << 8),
                (unsigned)qc[2] | ((qh1 & 0x07u) << 8),
                (unsigned)qc[3] | (((qh1 >> 4) & 0x07u) << 8),
            };
            float dls[4] = {dl1, dl1, dl2, dl2};
            float deltas[4] = {
                (qh0 & 0x08u) ? (-1.0f - IQ1S_DELTA) : (-1.0f + IQ1S_DELTA),
                (qh0 & 0x80u) ? (-1.0f - IQ1S_DELTA) : (-1.0f + IQ1S_DELTA),
                (qh1 & 0x08u) ? (-1.0f - IQ1S_DELTA) : (-1.0f + IQ1S_DELTA),
                (qh1 & 0x80u) ? (-1.0f - IQ1S_DELTA) : (-1.0f + IQ1S_DELTA),
            };
            int x_off = x_base + ib * 32;
            for (int l = 0; l < 4; ++l) {
                unsigned long long g = rsl::IQ1S_GRID_CUDA[idx_l[l]];
                float dl = dls[l];
                float delta_val = deltas[l];
                for (int j = 0; j < 8; ++j) {
                    signed char gj = (signed char)((g >> (j * 8)) & 0xFFu);
                    acc += dl * ((float)gj + delta_val) * x[x_off + 8 * l + j];
                }
            }
        }
    }
    return acc;
}

// NVFP4: 9 B / 16 wts. { qs[8] (16 nibbles, INTERLEAVED lo->2j hi->2j+1),
// scale:fp8_e4m3 (byte 8) }. K % 16 == 0.
__device__ __forceinline__ float nvfp4_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 9;
        float scale = rsl_e4m3_to_f32(blk[8]);
        int xo = b * 16;
        for (int j = 0; j < 8; ++j) {
            unsigned char byte = blk[j];
            int lo = byte & 0x0F;
            int hi = (byte >> 4) & 0x0F;
            acc += scale * RSL_NVFP4_CODEBOOK[lo] * x[xo + j * 2];
            acc += scale * RSL_NVFP4_CODEBOOK[hi] * x[xo + j * 2 + 1];
        }
    }
    return acc;
}

// ---------- OCP Microscaling (MXFP4 / MXFP6 / MXFP8) ----------
// 32 elements per block, each with a trailing E8M0 shared-scale byte that
// multiplies every decoded element. Byte-exact ports of the gguf CPU
// reference dequant_mxfp4/6/8; the element order + `scale * decode * x`
// accumulation match the NVFP4 kernel above so --cuda-parity agrees.

// MXFP4: 17 B / 32 wts. { qs:[u8;16], scale:e8m0 (byte 16) }. Each qs byte
// packs two E2M1 nibbles: low nibble -> element 2j, high -> element 2j+1
// (reuses the NVFP4 E2M1 codebook). K % 32 == 0.
__device__ __forceinline__ float mxfp4_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 17;
        float scale = rsl_e8m0_to_f32(blk[16]);
        int xo = b * 32;
        for (int j = 0; j < 16; ++j) {
            unsigned char byte = blk[j];
            int lo = byte & 0x0F;
            int hi = (byte >> 4) & 0x0F;
            acc += scale * RSL_NVFP4_CODEBOOK[lo] * x[xo + j * 2];
            acc += scale * RSL_NVFP4_CODEBOOK[hi] * x[xo + j * 2 + 1];
        }
    }
    return acc;
}

// MXFP6: 25 B / 32 wts. { qs:[u8;24] LE bitstream of 32 six-bit E3M2 codes,
// scale:e8m0 (byte 24) }. Element j occupies bits [6j, 6j+6); a 6-bit code
// can straddle a byte boundary, so read a 16-bit window
// { codes[byte_idx], codes[byte_idx+1] } and shift right by (6j % 8). The
// high byte reads as 0 once past the 24-byte code region (only the final
// code touches that, and its top bits are unused). K % 32 == 0.
__device__ __forceinline__ float mxfp6_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 25;
        const unsigned char *codes = blk;              // qs[0..24]
        float scale = rsl_e8m0_to_f32(blk[24]);
        int xo = b * 32;
        for (int j = 0; j < 32; ++j) {
            int bitpos = j * 6;
            int byte_idx = bitpos >> 3;                // bitpos / 8
            int bit_off = bitpos & 7;                  // bitpos % 8
            unsigned int lo = codes[byte_idx];
            unsigned int hi = (byte_idx + 1 < 24) ? (unsigned int)codes[byte_idx + 1] : 0u;
            unsigned int word = lo | (hi << 8);
            unsigned char code = (unsigned char)((word >> bit_off) & 0x3Fu);
            acc += scale * rsl_e3m2_to_f32(code) * x[xo + j];
        }
    }
    return acc;
}

// MXFP8: 33 B / 32 wts. { qs:[u8;32] one E4M3 byte per element,
// scale:e8m0 (byte 32) }. K % 32 == 0.
__device__ __forceinline__ float mxfp8_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 33;
        float scale = rsl_e8m0_to_f32(blk[32]);
        int xo = b * 32;
        for (int j = 0; j < 32; ++j) {
            acc += scale * rsl_e4m3_to_f32(blk[j]) * x[xo + j];
        }
    }
    return acc;
}

