// ============================================================
// Additional packed matvecs (byte-exact ports of the CPU reference
// impls in rustllama-kernels-cpu/src/lib.rs + nvfp4.rs). One thread per
// output row; each `<fmt>_row_dot(row, x, bpr)` unpacks the fmt's block
// layout and accumulates in the SAME element order as the CPU scalar so
// `doctor --cuda-parity` matches within tolerance. All wired through the
// RSL_PACKED_MATVEC macro (single + batched) below.
// ============================================================

// ---- K-quant scale unpack (ggml get_scale_min_k4): 12 packed bytes ->
// eight 6-bit `sc` (scales) + eight 6-bit `mn` (mins). Same code as the
// inline unpack in q4_k_row_dot_warp; shared by Q5_K (Q4_K keeps its inline copy).
__device__ __forceinline__ void rsl_unpack_q4k_scales(const unsigned char *sb,
                                                      unsigned char sc[8],
                                                      unsigned char mn[8]) {
    for (int j = 0; j < 8; ++j) {
        if (j < 4) {
            sc[j] = sb[j] & 0x3F;
            mn[j] = sb[j + 4] & 0x3F;
        } else {
            sc[j] = (sb[j + 4] & 0x0F) | ((sb[j - 4] >> 6) << 4);
            mn[j] = (sb[j + 4] >> 4) | ((sb[j] >> 6) << 4);
        }
    }
}

// ============================================================
// Q4_K prefill GEMM (Phase 1): REGISTER-BLOCKED tiled GEMM, f32 accumulate — a
// BIT-EXACT replacement for the batched matvec. Prefill is matvec-COMPUTE-bound
// (~linear in tokens, ~4% of f32 peak on a naive kernel), so the lever is ILP +
// arithmetic intensity, not just weight reuse: each thread computes a TM×TN
// micro-tile of outputs with register accumulators (TM·TN independent FMAs per
// k-step to hide latency), over a BM×BN block tile staged in shared memory. The
// weight super-block is DEQUANTIZED to f32 into shared on the way in (BK=32
// aligns to one Q4_K sub-block = one sc/mn), reused across the BN-token tile.
// Shared is transposed ([BK][BM]/[BK][BN]) for the inner loop. Bit-identical to
// the scalar Q4_K reference up to f32 reduction order. out[N,M] = x[N,K] .
// W[M,K]^T, W = Q4_K packed (144 B / 256 wt), K % 256 == 0.
// ============================================================
#define RSL_Q4K_GEMM_BM 64
#define RSL_Q4K_GEMM_BN 64
#define RSL_Q4K_GEMM_BK 32 // one Q4_K sub-block (one sc/mn)
#define RSL_Q4K_GEMM_TM 4  // rows per thread
#define RSL_Q4K_GEMM_TN 4  // tokens per thread
// threads = (BM/TM)*(BN/TN) = 16*16 = 256

__global__ void gemm_q4_k_f32_rb_kernel(const unsigned char *w, const float *x,
                                        float *out, int M, int K, int N) {
    __shared__ float As[RSL_Q4K_GEMM_BK][RSL_Q4K_GEMM_BM]; // dequant weights [k][row]
    __shared__ float Bs[RSL_Q4K_GEMM_BK][RSL_Q4K_GEMM_BN]; // activations   [k][token]
    const int rowBase = blockIdx.x * RSL_Q4K_GEMM_BM;
    const int tokBase = blockIdx.y * RSL_Q4K_GEMM_BN;
    const int tr = threadIdx.y; // 0..15 — micro-tile row index
    const int tc = threadIdx.x; // 0..15 — micro-tile token index
    const int nthreads = (RSL_Q4K_GEMM_BM / RSL_Q4K_GEMM_TM) *
                         (RSL_Q4K_GEMM_BN / RSL_Q4K_GEMM_TN); // 256
    const int tid = tr * (RSL_Q4K_GEMM_BN / RSL_Q4K_GEMM_TN) + tc;
    const int bpr = K / 256; // super-blocks per row
    float acc[RSL_Q4K_GEMM_TM][RSL_Q4K_GEMM_TN];
#pragma unroll
    for (int i = 0; i < RSL_Q4K_GEMM_TM; ++i)
#pragma unroll
        for (int j = 0; j < RSL_Q4K_GEMM_TN; ++j) acc[i][j] = 0.0f;

    const int ktiles = K / RSL_Q4K_GEMM_BK; // K/32
    for (int kt = 0; kt < ktiles; ++kt) {
        // Stage As[BK][BM] — dequant the BM weight rows' sub-block kt. All BK=32
        // weights of a (row, k-tile) live in the SAME super-block + sub-block
        // (BK aligns to one), so unpack d/dmin/sc/mn ONCE per row and read the 32
        // contiguous qs bytes — one thread per row (sbi = kt/8, sub-block = kt%8).
        {
            const int sbi = kt >> 3; // super-block (kt / 8)
            const int s = kt & 7;    // sub-block within super-block (kt % 8)
            const int hi = s & 1;    // odd sub-block -> high nibbles
            for (int rl = tid; rl < RSL_Q4K_GEMM_BM; rl += nthreads) {
                int mg = rowBase + rl;
                float dsc = 0.0f, dm = 0.0f;
                const unsigned char *qb = nullptr;
                if (mg < M) {
                    const unsigned char *blk = w + ((size_t)mg * bpr + sbi) * 144;
                    float d = rsl_f16_bits_to_f32((unsigned short)blk[0] | ((unsigned short)blk[1] << 8));
                    float dmin = rsl_f16_bits_to_f32((unsigned short)blk[2] | ((unsigned short)blk[3] << 8));
                    const unsigned char *sb = blk + 4;
                    unsigned char sc, mn;
                    if (s < 4) {
                        sc = sb[s] & 0x3F;
                        mn = sb[s + 4] & 0x3F;
                    } else {
                        sc = (sb[s + 4] & 0x0F) | ((sb[s - 4] >> 6) << 4);
                        mn = (sb[s + 4] >> 4) | ((sb[s] >> 6) << 4);
                    }
                    dsc = d * (float)sc;
                    dm = dmin * (float)mn;
                    qb = blk + 16 + (s >> 1) * 32; // this sub-block's 32 qs bytes
                }
#pragma unroll
                for (int kk = 0; kk < RSL_Q4K_GEMM_BK; ++kk) {
                    float val = 0.0f;
                    if (mg < M) {
                        unsigned char b = qb[kk];
                        int nib = hi ? (b >> 4) : (b & 0x0F);
                        val = dsc * (float)nib - dm;
                    }
                    As[kk][rl] = val;
                }
            }
        }
        // Stage Bs[BK][BN] — the BN tokens' sub-block kt.
        for (int e = tid; e < RSL_Q4K_GEMM_BN * RSL_Q4K_GEMM_BK; e += nthreads) {
            int tl = e % RSL_Q4K_GEMM_BN;
            int kk = e / RSL_Q4K_GEMM_BN;
            int ng = tokBase + tl;
            int kg = kt * RSL_Q4K_GEMM_BK + kk;
            Bs[kk][tl] = (ng < N) ? x[(size_t)ng * K + kg] : 0.0f;
        }
        __syncthreads();
#pragma unroll
        for (int k = 0; k < RSL_Q4K_GEMM_BK; ++k) {
            float ar[RSL_Q4K_GEMM_TM], br[RSL_Q4K_GEMM_TN];
#pragma unroll
            for (int i = 0; i < RSL_Q4K_GEMM_TM; ++i)
                ar[i] = As[k][tr * RSL_Q4K_GEMM_TM + i];
#pragma unroll
            for (int j = 0; j < RSL_Q4K_GEMM_TN; ++j)
                br[j] = Bs[k][tc * RSL_Q4K_GEMM_TN + j];
#pragma unroll
            for (int i = 0; i < RSL_Q4K_GEMM_TM; ++i)
#pragma unroll
                for (int j = 0; j < RSL_Q4K_GEMM_TN; ++j) acc[i][j] += ar[i] * br[j];
        }
        __syncthreads();
    }
    // Write out[token][row] = acc.
#pragma unroll
    for (int i = 0; i < RSL_Q4K_GEMM_TM; ++i) {
        int mg = rowBase + tr * RSL_Q4K_GEMM_TM + i;
        if (mg >= M) continue;
#pragma unroll
        for (int j = 0; j < RSL_Q4K_GEMM_TN; ++j) {
            int ng = tokBase + tc * RSL_Q4K_GEMM_TN + j;
            if (ng < N) out[(size_t)ng * M + mg] = acc[i][j];
        }
    }
}

// out[N,M] = x[N,K] . W[M,K]^T, W = Q4_K packed. K % 256 == 0.
extern "C" int rsl_cuda_gemm_q4_k_f32(rsl_cuda_stream *s, const void *w,
                                      const float *x, float *out, int M, int K,
                                      int N) {
    if (!s || !w || !x || !out || M <= 0 || K <= 0 || N <= 0 || (K % 256) != 0)
        return -1;
    cudaSetDevice(s->device);
    dim3 block(RSL_Q4K_GEMM_BN / RSL_Q4K_GEMM_TN, RSL_Q4K_GEMM_BM / RSL_Q4K_GEMM_TM); // 16x16
    dim3 grid((unsigned)((M + RSL_Q4K_GEMM_BM - 1) / RSL_Q4K_GEMM_BM),
              (unsigned)((N + RSL_Q4K_GEMM_BN - 1) / RSL_Q4K_GEMM_BN));
    gemm_q4_k_f32_rb_kernel<<<grid, block, 0, s->stream>>>(
        (const unsigned char *)w, x, out, M, K, N);
    return rsl_cuda_check("rsl_cuda_gemm_q4_k_f32");
}

// ============================================================
// Q4_K prefill GEMM — Phase 2: int8 TENSOR CORES (W8A8). Same 64x64/BK=32 tiling
// as the f32 GEMM, but the inner product is the s8 tensor-core MMA
// (nvcuda::wmma 16x16x16, legal on sm_72+ — the whole release arch list). LOSSY:
// activations are quantized to int8 (q4k_quant_act_kernel emits xq + per-32 scale
// xs + per-32 Σ xsum). Per Q4_K sub-block (32 wide = 2 WMMA k=16 steps) the MMA
// gives the exact int32 dot S1 = Σ(nibble·q_x); we then fold the per-row weight
// scale (d·sc / dmin·mn) and per-token activation scale/sum in f32 via the ggml
// identity y = xs·(d·sc·S1 − dmin·mn·Σq_x), accumulating across sub-blocks — the
// "fresh-accumulator-per-block → store → scale-in-f32" pattern (store_matrix_sync
// to shared avoids relying on the opaque accumulator fragment layout). One warp
// per 16x16 output sub-tile; 16 warps / 64x64 block. Graded vs the FAIR W8A8
// reference (int8 is exact; only activation rounding differs). out[N,M] =
// x[N,K]·W[M,K]^T, K % 256 == 0.
// ============================================================
#define RSL_Q4K_TC_BM 64
#define RSL_Q4K_TC_BN 64
#define RSL_Q4K_TC_WARPS 16 // 4x4 grid of 16x16 sub-tiles -> 512 threads

__global__ void gemm_q4_k_w8a8_tc_kernel(const unsigned char *w,
                                         const signed char *xq, const float *xs,
                                         const int *xsum, float *out, int M, int K,
                                         int N) {
    __shared__ signed char As[RSL_Q4K_TC_BM][32]; // weight nibbles  [m][k]
    __shared__ signed char Bs[RSL_Q4K_TC_BN][32]; // int8 activations [n][k]
    __shared__ float dsc[RSL_Q4K_TC_BM];          // per-row d*sc for this sub-block
    __shared__ float dmn[RSL_Q4K_TC_BM];          // per-row dmin*mn
    __shared__ float xscl[RSL_Q4K_TC_BN];         // per-token activation scale
    __shared__ int xsm[RSL_Q4K_TC_BN];            // per-token Σ int8 codes
    __shared__ int Cs[RSL_Q4K_TC_WARPS][16][16];  // per-warp int32 MMA result

    const int rowBase = blockIdx.x * RSL_Q4K_TC_BM;
    const int tokBase = blockIdx.y * RSL_Q4K_TC_BN;
    const int warpId = threadIdx.y; // 0..15
    const int lane = threadIdx.x;   // 0..31
    const int tid = warpId * 32 + lane;
    const int nthreads = RSL_Q4K_TC_WARPS * 32; // 512
    const int wr = warpId >> 2;     // 0..3 — which 16-row band
    const int wc = warpId & 3;      // 0..3 — which 16-token band
    const int m0 = rowBase + wr * 16;
    const int n0 = tokBase + wc * 16;
    const int bpr = K / 256; // super-blocks per row
    const int spr = K / 32;  // sub-blocks per row

    float cacc[8];
#pragma unroll
    for (int c = 0; c < 8; ++c) cacc[c] = 0.0f;

    for (int g = 0; g < spr; ++g) {
        const int sbi = g >> 3; // super-block (g / 8)
        const int s = g & 7;    // sub-block within super-block
        const int hi = s & 1;
        // Per-row weight scale (d*sc, dmin*mn) — one thread per row, unpack once.
        if (tid < RSL_Q4K_TC_BM) {
            int mg = rowBase + tid;
            float a = 0.0f, b = 0.0f;
            if (mg < M) {
                const unsigned char *blk = w + ((size_t)mg * bpr + sbi) * 144;
                float d = rsl_f16_bits_to_f32((unsigned short)blk[0] | ((unsigned short)blk[1] << 8));
                float dmin = rsl_f16_bits_to_f32((unsigned short)blk[2] | ((unsigned short)blk[3] << 8));
                const unsigned char *sb = blk + 4;
                unsigned char sc, mn;
                if (s < 4) {
                    sc = sb[s] & 0x3F;
                    mn = sb[s + 4] & 0x3F;
                } else {
                    sc = (sb[s + 4] & 0x0F) | ((sb[s - 4] >> 6) << 4);
                    mn = (sb[s + 4] >> 4) | ((sb[s] >> 6) << 4);
                }
                a = d * (float)sc;
                b = dmin * (float)mn;
            }
            dsc[tid] = a;
            dmn[tid] = b;
        }
        // Stage weight nibbles -> As[m][k] (int8).
        for (int e = tid; e < RSL_Q4K_TC_BM * 32; e += nthreads) {
            int rl = e >> 5;  // row (e / 32)
            int kk = e & 31;  // k within sub-block
            int mg = rowBase + rl;
            signed char nib = 0;
            if (mg < M) {
                const unsigned char *blk = w + ((size_t)mg * bpr + sbi) * 144;
                unsigned char bqt = blk[16 + (s >> 1) * 32 + kk];
                nib = (signed char)(hi ? (bqt >> 4) : (bqt & 0x0F));
            }
            As[rl][kk] = nib;
        }
        // Stage int8 activations -> Bs[n][k].
        for (int e = tid; e < RSL_Q4K_TC_BN * 32; e += nthreads) {
            int tl = e >> 5;
            int kk = e & 31;
            int ng = tokBase + tl;
            Bs[tl][kk] = (ng < N) ? xq[(size_t)ng * K + (size_t)g * 32 + kk] : (signed char)0;
        }
        // Per-token activation scale + Σ.
        if (tid < RSL_Q4K_TC_BN) {
            int ng = tokBase + tid;
            xscl[tid] = (ng < N) ? xs[(size_t)ng * spr + g] : 0.0f;
            xsm[tid] = (ng < N) ? xsum[(size_t)ng * spr + g] : 0;
        }
        __syncthreads();

        // S1 = Σ_k(nibble · q_x) over the 32-wide sub-block, into Cs[warpId].
#if defined(__CUDA_ARCH__) && (__CUDA_ARCH__ >= 720)
        nvcuda::wmma::fragment<nvcuda::wmma::matrix_a, 16, 16, 16, signed char,
                               nvcuda::wmma::row_major> a_frag;
        nvcuda::wmma::fragment<nvcuda::wmma::matrix_b, 16, 16, 16, signed char,
                               nvcuda::wmma::col_major> b_frag;
        nvcuda::wmma::fragment<nvcuda::wmma::accumulator, 16, 16, 16, int> acc_frag;
        nvcuda::wmma::fill_fragment(acc_frag, 0);
#pragma unroll
        for (int kk = 0; kk < 32; kk += 16) {
            nvcuda::wmma::load_matrix_sync(a_frag, &As[wr * 16][kk], 32);
            nvcuda::wmma::load_matrix_sync(b_frag, &Bs[wc * 16][kk], 32);
            nvcuda::wmma::mma_sync(acc_frag, a_frag, b_frag, acc_frag);
        }
        nvcuda::wmma::store_matrix_sync(&Cs[warpId][0][0], acc_frag, 16,
                                        nvcuda::wmma::mem_row_major);
#else
        // Scalar fallback (arch < sm_72, never in the release list): same int32 dot.
#pragma unroll
        for (int c = 0; c < 8; ++c) {
            int e = lane + c * 32;
            int mi = e >> 4, nj = e & 15;
            int acc_i = 0;
            for (int kk = 0; kk < 32; ++kk)
                acc_i += (int)As[wr * 16 + mi][kk] * (int)Bs[wc * 16 + nj][kk];
            Cs[warpId][mi][nj] = acc_i;
        }
#endif
        __syncwarp();
        // Scale pass: fold the f32 scales into the running f32 accumulator.
#pragma unroll
        for (int c = 0; c < 8; ++c) {
            int e = lane + c * 32;
            int mi = e >> 4, nj = e & 15;
            int row = wr * 16 + mi; // block-tile row (0..63)
            int tok = wc * 16 + nj; // block-tile token (0..63)
            cacc[c] += xscl[tok] * (dsc[row] * (float)Cs[warpId][mi][nj] -
                                    dmn[row] * (float)xsm[tok]);
        }
        __syncthreads(); // before the next sub-block overwrites shared
    }

    // Write out[token][row].
#pragma unroll
    for (int c = 0; c < 8; ++c) {
        int e = lane + c * 32;
        int mi = e >> 4, nj = e & 15;
        int mg = m0 + mi;
        int ng = n0 + nj;
        if (mg < M && ng < N) out[(size_t)ng * M + mg] = cacc[c];
    }
}

// Quant pre-pass (emit xq + xs + xsum) + int8-TC GEMM, persistent scratch.
extern "C" int rsl_cuda_gemm_q4_k_w8a8_tc(rsl_cuda_stream *s, const void *w,
                                          const float *x, float *out, int M, int K,
                                          int N) {
    if (!s || !w || !x || !out || M <= 0 || K <= 0 || N <= 0 || (K % 256) != 0)
        return -1;
    cudaSetDevice(s->device);
    size_t ne = (size_t)N * K;
    size_t nsub = (size_t)N * (K / 32);
    if (rsl_q4k_ensure_scratch(s, ne, nsub, nsub) != 0)
        return -2;
    signed char *xq = s->q4k_act_xq;
    float *xs = s->q4k_act_xs;
    int *xsum = s->q4k_xsum;
    dim3 qb(32, 8);
    dim3 qg((unsigned)((ne / 32 + 7) / 8));
    q4k_quant_act_kernel<<<qg, qb, 0, s->stream>>>(x, xq, xs, xsum, (int)ne);
    dim3 block(32, RSL_Q4K_TC_WARPS);
    dim3 grid((unsigned)((M + RSL_Q4K_TC_BM - 1) / RSL_Q4K_TC_BM),
              (unsigned)((N + RSL_Q4K_TC_BN - 1) / RSL_Q4K_TC_BN));
    gemm_q4_k_w8a8_tc_kernel<<<grid, block, 0, s->stream>>>(
        (const unsigned char *)w, xq, xs, xsum, out, M, K, N);
    return rsl_cuda_check("rsl_cuda_gemm_q4_k_w8a8_tc");
}

// IQ4_NL / IQ4_XS 16-entry non-linear codebook (ggml kvalues_iq4nl).
// Read-only device global (divergent index -> global/L2 beats __constant__).
__device__ const signed char RSL_KVALUES_IQ4NL[16] = {
    -127, -104, -83, -65, -49, -35, -22, -10, 1, 13, 25, 38, 53, 69, 89, 113};

// NVFP4 E2M1 codebook (16 signed values, indexed by the 4-bit code).
__device__ const float RSL_NVFP4_CODEBOOK[16] = {
    0.0f, 0.5f, 1.0f, 1.5f, 2.0f, 3.0f, 4.0f, 6.0f,
    -0.0f, -0.5f, -1.0f, -1.5f, -2.0f, -3.0f, -4.0f, -6.0f};

// Decode an FP8 E4M3 byte to f32 (bit-exact port of nvfp4::e4m3_to_f32).
// The 0x7F/0xFF NaN slot decodes to NaN (matches the CPU reference; real
// NVFP4 weight scales never land there).
__device__ __forceinline__ float rsl_e4m3_to_f32(unsigned char b) {
    bool sign = (b & 0x80) != 0;
    int exp = (b >> 3) & 0x0F;
    int mant = b & 0x07;
    float val;
    if (exp == 0x0F && mant == 0x07) {
        val = __int_as_float(0x7fc00000);  // NaN
    } else if (exp == 0) {
        val = (float)mant * (1.0f / 512.0f);  // subnormal: mant * 2^-9
    } else {
        float m = 1.0f + (float)mant / 8.0f;  // normal: (1 + mant/8) * 2^(exp-7)
        val = ldexpf(m, exp - 7);
    }
    return sign ? -val : val;
}

// OCP E8M0 shared-scale byte -> f32 (bit-exact port of gguf
// dequant::e8m0_to_f32). 8-bit unsigned biased exponent (bias 127), no
// sign / mantissa: value = 2^(byte - 127). 0xFF is the reserved NaN; 0x00
// decodes to 2^-127 (the smallest MX block scale). Shared by MXFP4/6/8.
__device__ __forceinline__ float rsl_e8m0_to_f32(unsigned char b) {
    if (b == 0xFF) return __int_as_float(0x7fc00000);  // NaN
    return ldexpf(1.0f, (int)b - 127);
}

// OCP E3M2 (MXFP6 element) -> f32 (bit-exact port of gguf
// dequant::e3m2_to_f32). 6-bit code `s eee mm`: 1 sign / 3 exp (bias 3) /
// 2 mantissa. No Inf/NaN encodings (every bit pattern is finite).
__device__ __forceinline__ float rsl_e3m2_to_f32(unsigned char c) {
    bool sign = (c & 0x20) != 0;
    int exp = (c >> 2) & 0x07;
    int mant = c & 0x03;
    float val;
    if (exp == 0) {
        // Subnormal: (mant/4) * 2^(1 - bias), bias = 3 -> factor 2^-2.
        val = ((float)mant * 0.25f) * ldexpf(1.0f, -2);
    } else {
        val = (1.0f + (float)mant * 0.25f) * ldexpf(1.0f, exp - 3);
    }
    return sign ? -val : val;
}

