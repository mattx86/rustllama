struct rsl_cuda_stream {
    int device;
    cudaStream_t stream;
    // Persistent Q4_K int8-activation scratch (int8 codes + per-sub-block scales)
    // for the int8-TC GEMM, grown on demand and REUSED across calls. Allocating
    // this per call in the decode hot loop was what made the int8-activation path
    // ~4x slower; reuse keeps the quant pre-pass cheap.
    signed char *q4k_act_xq = nullptr;
    float *q4k_act_xs = nullptr;
    size_t q4k_act_xq_cap = 0; // bytes
    size_t q4k_act_xs_cap = 0; // floats
    // Per-sub-block Σ of int8 activation codes (the W8A8/TC −dmin·mn·Σq_x term);
    // only allocated for the int8-TC path.
    int *q4k_xsum = nullptr;
    size_t q4k_xsum_cap = 0; // ints
};

extern "C" rsl_cuda_stream *rsl_cuda_stream_create(int device_index) {
    int n = 0;
    if (cudaGetDeviceCount(&n) != cudaSuccess || device_index < 0 || device_index >= n) {
        return nullptr;
    }
    if (cudaSetDevice(device_index) != cudaSuccess) return nullptr;
    rsl_cuda_stream *s = new (std::nothrow) rsl_cuda_stream();
    if (!s) return nullptr;
    s->device = device_index;
    if (cudaStreamCreate(&s->stream) != cudaSuccess) {
        delete s;
        return nullptr;
    }
    return s;
}

extern "C" void rsl_cuda_stream_destroy(rsl_cuda_stream *s) {
    if (!s) return;
    cudaSetDevice(s->device);
    if (s->q4k_act_xq) cudaFree(s->q4k_act_xq);
    if (s->q4k_act_xs) cudaFree(s->q4k_act_xs);
    if (s->q4k_xsum) cudaFree(s->q4k_xsum);
    cudaStreamDestroy(s->stream);
    delete s;
}

extern "C" void *rsl_cuda_malloc_from_host(rsl_cuda_stream *s, const void *src,
                                           unsigned long long n_bytes) {
    if (!s || n_bytes == 0) return nullptr;
    cudaSetDevice(s->device);
    void *p = nullptr;
    if (cudaMalloc(&p, (size_t)n_bytes) != cudaSuccess) return nullptr;
    if (src) {
        if (cudaMemcpy(p, src, (size_t)n_bytes, cudaMemcpyHostToDevice) != cudaSuccess) {
            cudaFree(p);
            return nullptr;
        }
    }
    return p;
}

extern "C" void *rsl_cuda_malloc_device(rsl_cuda_stream *s, unsigned long long n_bytes) {
    return rsl_cuda_malloc_from_host(s, nullptr, n_bytes);
}

extern "C" void rsl_cuda_free(rsl_cuda_stream *s, void *dev_ptr) {
    if (!s || !dev_ptr) return;
    cudaSetDevice(s->device);
    cudaFree(dev_ptr);
}

extern "C" int rsl_cuda_memcpy_h2d(rsl_cuda_stream *s, void *dst_dev,
                                   const void *src_host, unsigned long long n_bytes) {
    if (!s) return -1;
    cudaSetDevice(s->device);
    return cudaMemcpy(dst_dev, src_host, (size_t)n_bytes, cudaMemcpyHostToDevice) == cudaSuccess
               ? 0
               : -1;
}

extern "C" int rsl_cuda_memcpy_d2h(rsl_cuda_stream *s, void *dst_host,
                                   const void *src_dev, unsigned long long n_bytes) {
    if (!s) return -1;
    cudaSetDevice(s->device);
    return cudaMemcpy(dst_host, src_dev, (size_t)n_bytes, cudaMemcpyDeviceToHost) == cudaSuccess
               ? 0
               : -1;
}

__device__ __forceinline__ float rsl_f16_bits_to_f32(unsigned short bits) {
    return __half2float(__ushort_as_half(bits));
}

// ---- PTQ1_0 (Bonsai ternary) packed matvec: one thread per output row --
// Block: 28 B / 128 weights { qs:[24], qh:[2], d:f16 }. Trit extraction is
// the CPU/SYCL 8-bit trick: q' = q*3^n (u8 wrap), trit = ((q'*3)>>8) - 1.
__device__ __forceinline__ float ptq1_0_row_dot(const unsigned char *row,
                                                 const float *x, int blocks_per_row) {
    const unsigned char pow3[5] = {1, 3, 9, 27, 81};
    float acc = 0.0f;
    for (int b = 0; b < blocks_per_row; ++b) {
        const unsigned char *blk = row + b * 28;
        const unsigned char *qs = blk;
        const unsigned char *qh = blk + 24;
        unsigned short d_bits =
            (unsigned short)blk[26] | ((unsigned short)blk[27] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        const int x_base = b * 128;
        float sum = 0.0f;
        for (int n = 0; n < 5; ++n) {
            unsigned char p3 = pow3[n];
            int e0 = x_base + n * 16;
            for (int mm = 0; mm < 16; ++mm) {
                unsigned char qv = (unsigned char)(qs[mm] * p3);
                int trit = (((int)qv * 3) >> 8) - 1;
                sum += (float)trit * x[e0 + mm];
            }
        }
        for (int n = 0; n < 5; ++n) {
            unsigned char p3 = pow3[n];
            int e0 = x_base + 80 + n * 8;
            for (int mm = 0; mm < 8; ++mm) {
                unsigned char qv = (unsigned char)(qs[16 + mm] * p3);
                int trit = (((int)qv * 3) >> 8) - 1;
                sum += (float)trit * x[e0 + mm];
            }
        }
        for (int n = 0; n < 4; ++n) {
            unsigned char p3 = pow3[n];
            int e0 = x_base + 120 + n * 2;
            for (int hh = 0; hh < 2; ++hh) {
                unsigned char qv = (unsigned char)(qh[hh] * p3);
                int trit = (((int)qv * 3) >> 8) - 1;
                sum += (float)trit * x[e0 + hh];
            }
        }
        acc += d * sum;
    }
    return acc;
}

__global__ void ptq1_0_matvec_kernel(const unsigned char *w_bytes, const float *x,
                                     float *out, int M, int K) {
    int m = blockIdx.x * blockDim.x + threadIdx.x;
    if (m >= M) return;
    const int blocks_per_row = K / 128;
    const int bytes_per_row = blocks_per_row * 28;
    out[m] = ptq1_0_row_dot(w_bytes + (size_t)m * bytes_per_row, x, blocks_per_row);
}

__global__ void ptq1_0_matvec_batched_kernel(const unsigned char *w_bytes,
                                             const float *x, float *out,
                                             int M, int K, int N) {
    int m = blockIdx.x * blockDim.x + threadIdx.x;
    int n = blockIdx.y;
    if (m >= M || n >= N) return;
    const int blocks_per_row = K / 128;
    const int bytes_per_row = blocks_per_row * 28;
    const float *x_row = x + (size_t)n * K;
    out[(size_t)n * M + m] =
        ptq1_0_row_dot(w_bytes + (size_t)m * bytes_per_row, x_row, blocks_per_row);
}

extern "C" int rsl_cuda_matvec_ptq1_0_packed_f32(rsl_cuda_stream *s,
                                                 const void *w_bytes_dev,
                                                 const float *x_dev, float *out_dev,
                                                 int M, int K) {
    if (!s || !w_bytes_dev || !x_dev || !out_dev || M <= 0 || K <= 0 || (K % 128) != 0) {
        return -1;
    }
    cudaSetDevice(s->device);
    int threads = 128;
    int blocks = (M + threads - 1) / threads;
    ptq1_0_matvec_kernel<<<blocks, threads, 0, s->stream>>>(
        (const unsigned char *)w_bytes_dev, x_dev, out_dev, M, K);
    return rsl_cuda_check("rsl_cuda_matvec_ptq1_0_packed_f32");
}

extern "C" int rsl_cuda_matvec_ptq1_0_packed_f32_batched(rsl_cuda_stream *s,
                                                         const void *w_bytes_dev,
                                                         const float *x_dev,
                                                         float *out_dev,
                                                         int M, int K, int N) {
    if (!s || !w_bytes_dev || !x_dev || !out_dev || M <= 0 || K <= 0 || N <= 0 ||
        (K % 128) != 0) {
        return -1;
    }
    cudaSetDevice(s->device);
    int threads = 128;
    dim3 blocks((M + threads - 1) / threads, (unsigned)N);
    ptq1_0_matvec_batched_kernel<<<blocks, threads, 0, s->stream>>>(
        (const unsigned char *)w_bytes_dev, x_dev, out_dev, M, K, N);
    return rsl_cuda_check("rsl_cuda_matvec_ptq1_0_packed_f32_batched");
}

// ---- Blockwise Prism Hadamard: out = WHT(signs*x)/sqrt(block) per span --
// One block per span; butterfly staged in shared memory with a barrier per
// stage (the SYCL kernel's CUDA companion).
__global__ void hadamard_forward_kernel(const float *x, const float *signs,
                                        float *out, int block, float inv_sqrt) {
    extern __shared__ float slm[];
    int blk = blockIdx.x;
    int lws = blockDim.x;
    int tid = threadIdx.x;
    int per_thread = block / lws;
    int base = blk * block;
    for (int i = 0; i < per_thread; ++i) {
        int e = tid * per_thread + i;
        slm[e] = x[base + e] * signs[base + e];
    }
    __syncthreads();
    for (int half = 1; half < block; half <<= 1) {
        for (int i = 0; i < per_thread; ++i) {
            int e = tid * per_thread + i;
            if (e < block / 2) {
                int lo = (e / half) * (half << 1) + (e % half);
                int hi = lo + half;
                float a = slm[lo];
                float bqv = slm[hi];
                slm[lo] = a + bqv;
                slm[hi] = a - bqv;
            }
        }
        __syncthreads();
    }
    for (int i = 0; i < per_thread; ++i) {
        int e = tid * per_thread + i;
        out[base + e] = slm[e] * inv_sqrt;
    }
}

extern "C" int rsl_cuda_hadamard_forward(rsl_cuda_stream *s, const float *x_dev,
                                         const float *signs_dev, float *out_dev,
                                         int n_elems, int block) {
    if (!s || !x_dev || !signs_dev || !out_dev || n_elems <= 0 || block <= 0 ||
        (n_elems % block) != 0 || (block & (block - 1)) != 0 || block > 4096) {
        return -1;
    }
    cudaSetDevice(s->device);
    int n_blocks = n_elems / block;
    int lws = block < 256 ? block : 256;
    float inv_sqrt = 1.0f / sqrtf((float)block);
    hadamard_forward_kernel<<<n_blocks, lws, (size_t)block * sizeof(float), s->stream>>>(
        x_dev, signs_dev, out_dev, block, inv_sqrt);
    return rsl_cuda_check("rsl_cuda_hadamard_forward");
}

// ============================================================
// K-quant packed matvecs (Q8_0 / Q4_K / Q6_K) — ONE WARP per row (32 lanes
// cooperate over the k-dimension; coalesced loads + a shfl reduce), device-
// pointer args. The dequant math is byte-exact with the SYCL/CPU reference,
// just distributed across the warp's lanes. RSL_PACKED_MATVEC_WARP (below)
// generates the single + batched kernels + launchers from each
// `<fmt>_row_dot_warp(row, x, bpr, lane)`.
// ============================================================

// Q8_0: 34 B / 32-weight block { f16 scale, 32 i8 }. K % 32 == 0.
// Warp-cooperative: lane `t` owns weight `t` of every block, so the warp's 32
// lanes read the 32 consecutive i8s (coalesced) + the 32 consecutive x floats
// and each accumulates its per-block products into a lane partial. The caller
// warp-reduces the 32 partials:
//   sum_t sum_b scale_b * w[b,t] * x[b,t] = sum_b scale_b * dot_b = row dot.
// (Summation order differs from the scalar reference → float reassociation,
// within `doctor --cuda-parity` tolerance.)
__device__ __forceinline__ float q8_0_row_dot_warp(const unsigned char *row,
                                                   const float *x, int bpr,
                                                   int lane) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 34;
        unsigned short sb = (unsigned short)blk[0] | ((unsigned short)blk[1] << 8);
        float scale = rsl_f16_bits_to_f32(sb);
        float w = (float)((signed char)blk[2 + lane]);
        acc += scale * w * x[b * 32 + lane];
    }
    return acc;
}

// Q4_K_M: 144 B / 256-weight super-block. K % 256 == 0.
// Warp-cooperative, ONE GROUP per lane: the 256 weights are 4 groups of 64
// (a group = 32 qs-bytes + two 6-bit scales + two 6-bit mins). Lane `t` owns
// group `t>>3` and the 4-byte chunk `(t&7)*4` within it, so it unpacks ONLY
// that group's 2 scales (not all 8) and handles 8 weights (4 lo + 4 hi).
// Instead of dequantizing each weight, accumulate the quantized dot Σ(q·x) and
// the activation sum Σx, then apply the scales ONCE per block via the ggml
// identity  y_group = d·sc·Σ(q·x) − dmin·mn·Σx  — far fewer per-weight FMAs.
// Byte loads (no alignment assumption). Numerically equivalent to the scalar
// reference (float reassociation only); the warp-reduce over the 32 lanes'
// partials yields the row dot. (A 2-way branch on group<2 is the only
// divergence; each side is a couple of mask/shift ops.)
__device__ __forceinline__ float q4_k_row_dot_warp(const unsigned char *row,
                                                   const float *x, int bpr,
                                                   int lane) {
    const int group = lane >> 3;      // 0..3  — which 64-weight group this lane serves
    const int lbase = (lane & 7) * 4; // 0..28 — weight/byte offset within the group
    const int j0 = group * 2;         // scale index for the lo nibbles
    const int j1 = group * 2 + 1;     // scale index for the hi nibbles
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 144;
        float d = rsl_f16_bits_to_f32((unsigned short)blk[0] | ((unsigned short)blk[1] << 8));
        float dmin = rsl_f16_bits_to_f32((unsigned short)blk[2] | ((unsigned short)blk[3] << 8));
        const unsigned char *sb = blk + 4;
        // This lane's group only (ggml get_scale_min_k4): two scales + two mins.
        unsigned char sc0, sc1, mn0, mn1;
        if (group < 2) { // indices j0,j1 are < 4: low 6 bits direct.
            sc0 = sb[j0] & 0x3F;
            mn0 = sb[j0 + 4] & 0x3F;
            sc1 = sb[j1] & 0x3F;
            mn1 = sb[j1 + 4] & 0x3F;
        } else {         // indices >= 4: splice sb[j+4] nibble with sb[j-4]/sb[j] top bits.
            sc0 = (sb[j0 + 4] & 0x0F) | ((sb[j0 - 4] >> 6) << 4);
            mn0 = (sb[j0 + 4] >> 4) | ((sb[j0] >> 6) << 4);
            sc1 = (sb[j1 + 4] & 0x0F) | ((sb[j1 - 4] >> 6) << 4);
            mn1 = (sb[j1 + 4] >> 4) | ((sb[j1] >> 6) << 4);
        }
        const unsigned char *qc = blk + 16 + group * 32 + lbase; // this lane's 4 bytes
        const int x_lo = b * 256 + group * 64 + lbase;
        const int x_hi = x_lo + 32;
        float dot_lo = 0.0f, dot_hi = 0.0f, xsum_lo = 0.0f, xsum_hi = 0.0f;
#pragma unroll
        for (int k = 0; k < 4; ++k) {
            unsigned char qb = qc[k];
            float xl = x[x_lo + k];
            float xh = x[x_hi + k];
            dot_lo += (float)(qb & 0x0F) * xl;
            dot_hi += (float)(qb >> 4) * xh;
            xsum_lo += xl;
            xsum_hi += xh;
        }
        acc += d * ((float)sc0 * dot_lo + (float)sc1 * dot_hi) -
               dmin * ((float)mn0 * xsum_lo + (float)mn1 * xsum_hi);
    }
    return acc;
}

// Q6_K: 210 B / 256-weight super-block. K % 256 == 0.
// Warp-cooperative: the scalar reference walks (n in 0..2) × (l in 0..32) = 64
// inner iterations, each emitting 4 weights (q1..q4) → 256. The warp maps lane
// `t` → l=t and runs the two n passes, so the 32 lanes read ql/qh/x at
// consecutive offsets (coalesced) and each lane accumulates its 2×4 = 8
// weights' products; the caller warp-reduces the 32 partials to the row dot.
__device__ __forceinline__ float q6_k_row_dot_warp(const unsigned char *row,
                                                   const float *x, int bpr,
                                                   int lane) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 210;
        const unsigned char *ql = blk;
        const unsigned char *qh = blk + 128;
        const signed char *scales = (const signed char *)(blk + 192);
        unsigned short d_bits = (unsigned short)blk[208] | ((unsigned short)blk[209] << 8);
        float d = rsl_f16_bits_to_f32(d_bits);
        int x_base = b * 256;
        int l = lane; // 0..31
#pragma unroll
        for (int n = 0; n < 2; ++n) {
            int is = l / 16 + n * 8;
            int qh_byte = qh[32 * n + l];
            int q1 = ((int)(ql[64 * n + l] & 0x0F) | (((qh_byte >> 0) & 0x03) << 4)) - 32;
            int q2 = ((int)(ql[64 * n + l + 32] & 0x0F) | (((qh_byte >> 2) & 0x03) << 4)) - 32;
            int q3 = ((int)(ql[64 * n + l] >> 4) | (((qh_byte >> 4) & 0x03) << 4)) - 32;
            int q4 = ((int)(ql[64 * n + l + 32] >> 4) | (((qh_byte >> 6) & 0x03) << 4)) - 32;
            float s0 = (float)scales[is];
            float s1 = (float)scales[is + 2];
            float s2 = (float)scales[is + 4];
            float s3 = (float)scales[is + 6];
            int base = n * 128 + l;
            acc += d * s0 * (float)q1 * x[x_base + base];
            acc += d * s1 * (float)q2 * x[x_base + base + 32];
            acc += d * s2 * (float)q3 * x[x_base + base + 64];
            acc += d * s3 * (float)q4 * x[x_base + base + 96];
        }
    }
    return acc;
}

// Generate `<name>` (single) + `<name>_batched` kernels and their extern-"C"
// launchers from a device `row_dot`. `kmod` = K divisor; `bpb`/`epb` =
// bytes/elements per block.
#define RSL_PACKED_MATVEC(NAME, ROWDOT, KMOD, BPB, EPB)                       \
    __global__ void NAME##_kernel(const unsigned char *w, const float *x,     \
                                  float *out, int M, int K) {                 \
        int m = blockIdx.x * blockDim.x + threadIdx.x;                        \
        if (m >= M) return;                                                   \
        int bpr = K / (EPB);                                                  \
        out[m] = ROWDOT(w + (size_t)m * bpr * (BPB), x, bpr);                 \
    }                                                                         \
    __global__ void NAME##_batched_kernel(const unsigned char *w,            \
                                          const float *x, float *out, int M,  \
                                          int K, int N) {                     \
        int m = blockIdx.x * blockDim.x + threadIdx.x;                        \
        if (m >= M) return;                                                   \
        int bpr = K / (EPB);                                                  \
        /* grid.y is capped at 65535; stride over the batch so all N rows  */ \
        /* are covered even when N exceeds the launch limit.               */ \
        for (int n = blockIdx.y; n < N; n += gridDim.y) {                    \
            out[(size_t)n * M + m] =                                          \
                ROWDOT(w + (size_t)m * bpr * (BPB), x + (size_t)n * K, bpr);  \
        }                                                                     \
    }                                                                         \
    extern "C" int rsl_cuda_##NAME(rsl_cuda_stream *s, const void *w,         \
                                   const float *x, float *out, int M, int K) {\
        if (!s || !w || !x || !out || M <= 0 || K <= 0 || (K % (KMOD)) != 0)  \
            return -1;                                                        \
        cudaSetDevice(s->device);                                            \
        int t = 128, b = (M + t - 1) / t;                                    \
        NAME##_kernel<<<b, t, 0, s->stream>>>((const unsigned char *)w, x,   \
                                              out, M, K);                     \
        return rsl_cuda_check("rsl_cuda_" #NAME);                            \
    }                                                                         \
    extern "C" int rsl_cuda_##NAME##_batched(rsl_cuda_stream *s,             \
                                             const void *w, const float *x,   \
                                             float *out, int M, int K,        \
                                             int N) {                         \
        if (!s || !w || !x || !out || M <= 0 || K <= 0 || N <= 0 ||          \
            (K % (KMOD)) != 0)                                                \
            return -1;                                                        \
        cudaSetDevice(s->device);                                            \
        int t = 128;                                                          \
        unsigned gy = (unsigned)(N < 65535 ? N : 65535);                     \
        dim3 b((M + t - 1) / t, gy);                                          \
        NAME##_batched_kernel<<<b, t, 0, s->stream>>>(                        \
            (const unsigned char *)w, x, out, M, K, N);                       \
        return rsl_cuda_check("rsl_cuda_" #NAME "_batched");                 \
    }

// Warp-cooperative variant of RSL_PACKED_MATVEC: ONE WARP (32 lanes) per output
// row instead of one thread. Each lane accumulates a partial over its share of
// the k-dimension via `<name>_row_dot_warp(row, x, bpr, lane)` (coalesced loads
// — adjacent lanes touch adjacent bytes), then the warp shfl-reduces to the row
// dot. This is the decode-perf fix: the scalar one-thread-per-row kernels were
// compute-bound at ~26% memory-bandwidth utilization (uncoalesced per-row reads
// + serial dequant on one thread); the warp form coalesces the weight stream
// and parallelizes the dequant 32×. Launch = 8 warps/block (block = 32×8); a
// warp is a fixed threadIdx.y with threadIdx.x the lane, so all 32 lanes share
// one row and the 0xffffffff shfl mask is always full.
#define RSL_PACKED_MATVEC_WARP(NAME, ROWDOTWARP, KMOD, BPB, EPB)               \
    __global__ void NAME##_kernel(const unsigned char *w, const float *x,     \
                                  float *out, int M, int K) {                 \
        int row = blockIdx.x * blockDim.y + threadIdx.y;                      \
        if (row >= M) return;                                                 \
        int lane = threadIdx.x;                                               \
        int bpr = K / (EPB);                                                  \
        float acc = ROWDOTWARP(w + (size_t)row * bpr * (BPB), x, bpr, lane);  \
        for (int off = warpSize >> 1; off > 0; off >>= 1)                     \
            acc += __shfl_down_sync(0xffffffffu, acc, off);                   \
        if (lane == 0) out[row] = acc;                                        \
    }                                                                         \
    __global__ void NAME##_batched_kernel(const unsigned char *w,            \
                                          const float *x, float *out, int M,  \
                                          int K, int N) {                     \
        int row = blockIdx.x * blockDim.y + threadIdx.y;                      \
        if (row >= M) return;                                                 \
        int lane = threadIdx.x;                                               \
        int bpr = K / (EPB);                                                  \
        const unsigned char *rowp = w + (size_t)row * bpr * (BPB);            \
        /* grid.y strides the batch (capped at 65535). */                     \
        for (int n = blockIdx.y; n < N; n += gridDim.y) {                    \
            float acc = ROWDOTWARP(rowp, x + (size_t)n * K, bpr, lane);       \
            for (int off = warpSize >> 1; off > 0; off >>= 1)                 \
                acc += __shfl_down_sync(0xffffffffu, acc, off);              \
            if (lane == 0) out[(size_t)n * M + row] = acc;                    \
        }                                                                     \
    }                                                                         \
    extern "C" int rsl_cuda_##NAME(rsl_cuda_stream *s, const void *w,         \
                                   const float *x, float *out, int M, int K) {\
        if (!s || !w || !x || !out || M <= 0 || K <= 0 || (K % (KMOD)) != 0)  \
            return -1;                                                        \
        cudaSetDevice(s->device);                                            \
        dim3 block(32, 8);                                                    \
        dim3 grid((unsigned)((M + 7) / 8));                                   \
        NAME##_kernel<<<grid, block, 0, s->stream>>>(                        \
            (const unsigned char *)w, x, out, M, K);                          \
        return rsl_cuda_check("rsl_cuda_" #NAME);                            \
    }                                                                         \
    extern "C" int rsl_cuda_##NAME##_batched(rsl_cuda_stream *s,             \
                                             const void *w, const float *x,   \
                                             float *out, int M, int K,        \
                                             int N) {                         \
        if (!s || !w || !x || !out || M <= 0 || K <= 0 || N <= 0 ||          \
            (K % (KMOD)) != 0)                                                \
            return -1;                                                        \
        cudaSetDevice(s->device);                                            \
        unsigned gy = (unsigned)(N < 65535 ? N : 65535);                     \
        dim3 block(32, 8);                                                    \
        dim3 grid((unsigned)((M + 7) / 8), gy);                              \
        NAME##_batched_kernel<<<grid, block, 0, s->stream>>>(                \
            (const unsigned char *)w, x, out, M, K, N);                       \
        return rsl_cuda_check("rsl_cuda_" #NAME "_batched");                 \
    }

