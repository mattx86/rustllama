// ---------- Priority 3: Q3_K + PQ2_0 (parity-gap close) ----------

// Q3_K: 110 B / 256 wts. { hmask[32], qs[64], scales[12], d:f16 }.
// Byte-exact port of the CPU matvec_q3_k_w_f32_a scalar reference (and the
// SYCL matvec_q3_k_packed_f32_usm impl): the 12 scale bytes unpack via
// KMASK1/KMASK2 into sixteen 6-bit sub-scales (i8, bias 32); each 16-weight
// half-sub-block takes the low 2 bits of qs (0..3) and subtracts 4 when the
// matching hmask bit is CLEAR. `acc` accumulates directly, in the same nested
// (chunk -> j4 -> lo/hi 16-lane) order as the scalar so --cuda-parity matches.
__device__ __forceinline__ float q3_k_row_dot(const unsigned char *row,
                                              const float *x, int bpr) {
    const unsigned int KMASK1 = 0x03030303u;
    const unsigned int KMASK2 = 0x0f0f0f0fu;
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 110;
        const unsigned char *hmask = blk;            // [0..32)
        const unsigned char *qs = blk + 32;          // [32..96)
        const unsigned char *sc_raw = blk + 96;      // [96..108)
        float d_all = rsl_f16_bits_to_f32((unsigned short)blk[108]
                                          | ((unsigned short)blk[109] << 8));
        unsigned int aux[4];
        aux[0] = (unsigned)sc_raw[0] | ((unsigned)sc_raw[1] << 8)
               | ((unsigned)sc_raw[2] << 16) | ((unsigned)sc_raw[3] << 24);
        aux[1] = (unsigned)sc_raw[4] | ((unsigned)sc_raw[5] << 8)
               | ((unsigned)sc_raw[6] << 16) | ((unsigned)sc_raw[7] << 24);
        aux[2] = (unsigned)sc_raw[8] | ((unsigned)sc_raw[9] << 8)
               | ((unsigned)sc_raw[10] << 16) | ((unsigned)sc_raw[11] << 24);
        unsigned int tmp = aux[2];
        aux[2] = ((aux[0] >> 4) & KMASK2) | (((tmp >> 4) & KMASK1) << 4);
        aux[3] = ((aux[1] >> 4) & KMASK2) | (((tmp >> 6) & KMASK1) << 4);
        aux[0] = (aux[0] & KMASK2) | ((tmp & KMASK1) << 4);
        aux[1] = (aux[1] & KMASK2) | (((tmp >> 2) & KMASK1) << 4);
        signed char scales[16];
        for (int j = 0; j < 16; ++j)
            scales[j] = (signed char)((aux[j >> 2] >> ((j & 3) * 8)) & 0xFF);
        const int x_base = b * 256;
        int q_cursor = 0, x_off = 0, is = 0;
        unsigned char m_bit = 1;
        for (int chunk = 0; chunk < 2; ++chunk) {
            unsigned int shift = 0;
            for (int j4 = 0; j4 < 4; ++j4) {
                float dl = d_all * ((float)scales[is] - 32.0f);
                ++is;
                for (int l = 0; l < 16; ++l) {
                    int lo = (int)((qs[q_cursor + l] >> shift) & 3);
                    int hi_sub = (hmask[l] & m_bit) != 0 ? 0 : 4;
                    acc += dl * (float)(lo - hi_sub) * x[x_base + x_off + l];
                }
                x_off += 16;
                dl = d_all * ((float)scales[is] - 32.0f);
                ++is;
                for (int l = 0; l < 16; ++l) {
                    int lo = (int)((qs[q_cursor + l + 16] >> shift) & 3);
                    int hi_sub = (hmask[l + 16] & m_bit) != 0 ? 0 : 4;
                    acc += dl * (float)(lo - hi_sub) * x[x_base + x_off + l];
                }
                x_off += 16;
                shift += 2;
                m_bit = (unsigned char)(m_bit << 1);
            }
            q_cursor += 32;
        }
    }
    return acc;
}

// PQ2_0 (PrismML Bonsai 2-bit): 34 B / 128 wts. { d:f16, qs[32] } — four
// 2-bit codes per qs byte, low bits first; weight = d * (code - 1).
// Byte-exact port of the CPU matvec_pq2_0_w_f32_a / SYCL PQ2_0 impl:
// accumulate (code-1)*x across the 128-wide block, then scale once per block
// (acc += d * sum), matching the scalar's per-block grouping.
__device__ __forceinline__ float pq2_0_row_dot(const unsigned char *row,
                                               const float *x, int bpr) {
    float acc = 0.0f;
    for (int b = 0; b < bpr; ++b) {
        const unsigned char *blk = row + b * 34;
        float d = rsl_f16_bits_to_f32((unsigned short)blk[0]
                                      | ((unsigned short)blk[1] << 8));
        const unsigned char *qs = blk + 2;
        int x_off = b * 128;
        float sum = 0.0f;
        for (int j = 0; j < 128; ++j) {
            int qv = (int)((qs[j / 4] >> ((j % 4) * 2)) & 0x3) - 1;
            sum += (float)qv * x[x_off + j];
        }
        acc += d * sum;
    }
    return acc;
}

