    #[test]
    fn multi_flight_admits_up_to_capacity_then_queues() {
        // 3-slot scheduler admits 3 directly into active slots; the 4th
        // and 5th go to the waiting queue.
        let s = MultiFlightScheduler::new(3);
        let a = s.admit(slot(RequestId(0), SlotState::Decoding));
        let b = s.admit(slot(RequestId(0), SlotState::Decoding));
        let c = s.admit(slot(RequestId(0), SlotState::Decoding));
        let _d = s.admit(slot(RequestId(0), SlotState::Decoding));
        let _e = s.admit(slot(RequestId(0), SlotState::Decoding));

        let (active, waiting) = s.depth();
        assert_eq!(active, 3, "first 3 must occupy active slots");
        assert_eq!(waiting, 2, "extra admissions queue");
        assert_eq!(s.pending(), 5);

        // Stepping returns every active Decoding slot.
        let step = s.step();
        assert_eq!(step.decode_ids.len(), 3);

        // Completing one promotes a waiter into the active set.
        s.complete(a);
        let (active, waiting) = s.depth();
        assert_eq!(active, 3, "waiter promoted into freed slot");
        assert_eq!(waiting, 1);

        // Drain everything.
        s.complete(b);
        s.complete(c);
        let (_active, waiting) = s.depth();
        assert_eq!(waiting, 0);
    }

