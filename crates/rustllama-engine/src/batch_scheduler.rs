    #[test]
    fn pool_admit_stamps_monotonic_admit_seq() {
        // Each admission gets a strictly larger admit_seq. Used by
        // the priority queue's FIFO-within-priority tiebreaker.
        let mut p = SlotPool::new(8);
        let id1 = RequestId(1);
        let id2 = RequestId(2);
        p.admit(slot(id1, SlotState::Pending));
        p.admit(slot(id2, SlotState::Pending));
        let s1_seq = p.find(id1).unwrap().admit_seq;
        let s2_seq = p.find(id2).unwrap().admit_seq;
        assert!(s2_seq > s1_seq, "admit_seq must be monotonic: {s1_seq} {s2_seq}");
    }

    #[test]
    fn pool_pulls_highest_priority_waiter_first() {
        // Capacity 1 → first admit slots, rest queue. On complete,
        // the waiter with the highest priority drains in (FIFO
        // tiebreaker within a priority level).
        let mut p = SlotPool::new(1);
        // Active slot — fills capacity.
        p.admit(slot(RequestId(1), SlotState::Decoding));
        // Three waiters in admit order with mixed priorities.
        // Expect drain order: HIGH (id=10) → DEFAULT (id=20) → LOW (id=30).
        p.admit(slot_with_priority(RequestId(30), Priority::LOW));
        p.admit(slot_with_priority(RequestId(10), Priority::HIGH));
        p.admit(slot_with_priority(RequestId(20), Priority::DEFAULT));

        // Complete the active slot → expect HIGH to drain in.
        p.complete(RequestId(1));
        assert_eq!(p.find(RequestId(10)).map(|s| s.request_id), Some(RequestId(10)));
        assert!(p.find(RequestId(20)).is_none());
        assert!(p.find(RequestId(30)).is_none());

        // Complete the HIGH slot → DEFAULT drains next.
        p.complete(RequestId(10));
        assert_eq!(p.find(RequestId(20)).map(|s| s.request_id), Some(RequestId(20)));
        assert!(p.find(RequestId(30)).is_none());

        // Complete the DEFAULT slot → LOW drains last.
        p.complete(RequestId(20));
        assert_eq!(p.find(RequestId(30)).map(|s| s.request_id), Some(RequestId(30)));
    }

    #[test]
    fn pool_fifo_within_priority_on_tie() {
        // Two waiters at the same priority: older `admit_seq` wins.
        let mut p = SlotPool::new(1);
        p.admit(slot(RequestId(1), SlotState::Decoding));
        p.admit(slot_with_priority(RequestId(100), Priority::DEFAULT)); // older
        p.admit(slot_with_priority(RequestId(200), Priority::DEFAULT)); // newer

        p.complete(RequestId(1));
        // RequestId(100) drained first.
        assert!(p.find(RequestId(100)).is_some());
        assert!(p.find(RequestId(200)).is_none());
    }

